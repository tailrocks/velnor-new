use std::path::Path;

use super::{generator_owned, velnor_gen_owned};

#[test]
fn the_workflows_namespace_is_generator_owned_except_the_release_workflow_of_the_rust_tools()
-> Result<(), Box<dyn std::error::Error>> {
    let source = tempfile::NamedTempFile::new()?;
    std::fs::write(source.path(), "name: Plain\n")?;
    let metadata = std::fs::metadata(source.path())?;
    let cases = [
        ("workflows", false),
        ("workflows/ci.yml", true),
        ("workflows/manual.yml", true),
        ("workflows/release-rust-ci-tools.yml", false),
        ("workflows/release-rust-ci-tools.yml.bak", true),
        ("workflows/nested/release-rust-ci-tools.yml", true),
        ("release-rust-ci-tools.yml", false),
    ];
    for (path, owned) in cases {
        assert_eq!(
            generator_owned(Path::new(path), source.path(), &metadata)?,
            owned,
            "{path}"
        );
    }
    Ok(())
}

#[test]
fn generator_owned_spares_only_a_velnor_gen_file_directly_in_workflows()
-> Result<(), Box<dyn std::error::Error>> {
    let directory = tempfile::tempdir()?;
    let cases = [
        (
            "workflows/rust-ci.yml",
            "# Generated by velnor-gen. Change it.\nname: A\n",
            false,
        ),
        (
            "workflows/bare.yml",
            "# Generated by velnor-gen.\nname: A\n",
            false,
        ),
        (
            "workflows/crlf.yml",
            "# Generated by velnor-gen.\r\nname: A\r\n",
            false,
        ),
        (
            "workflows/fork.yml",
            "# Generated by velnor-gen.fork\nname: A\n",
            true,
        ),
        (
            "workflows/nested/rust-ci.yml",
            "# Generated by velnor-gen.\nname: A\n",
            true,
        ),
    ];
    for (index, (path, contents, owned)) in cases.into_iter().enumerate() {
        let source = directory.path().join(index.to_string());
        std::fs::write(&source, contents)?;
        let metadata = std::fs::metadata(&source)?;
        assert_eq!(
            generator_owned(Path::new(path), &source, &metadata)?,
            owned,
            "{path}"
        );
    }
    let leaf = directory.path().join("leaf");
    std::fs::write(&leaf, "# Generated by velnor-gen.\n")?;
    assert!(!velnor_gen_owned(
        Path::new("workflows"),
        &leaf,
        &std::fs::metadata(&leaf)?
    )?);
    Ok(())
}
