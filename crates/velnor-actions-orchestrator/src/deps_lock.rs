use std::ffi::{OsStr, OsString};
use std::path::Path;
use std::time::Duration;

use serde::Deserialize;
use velnor_actions_contract::config::{DEPS_LOCK_PATH, PrivateSourcesConfig};
use velnor_actions_contract::deps_lock::{DEPS_LOCK_SCHEMA, DepsLock, LockedAsset, LockedGitTree};
use velnor_actions_mise::{PinnedTool, PinnedToolExec, ToolCatalog};

use crate::OrchestratorError;
use crate::config::{config_error, load_config};
use crate::internal::internal;
use crate::safe_read::{MAX_REPO_FILE_BYTES, RepoRead, read_repo_file};

const MAX_ASSET_HASH_BYTES: usize = 512 * 1024 * 1024;
const UPPER_HEX: &[u8; 16] = b"0123456789ABCDEF";
const API_JSON_BYTES: usize = 4 * 1024 * 1024;
const API_TIMEOUT: Duration = Duration::from_secs(120);
const LOCK_HEADER: &str = "# Generated by `velnor-actions deps lock`. Do not edit by hand.\n";

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct AssetObservation {
    pub sha256: String,
}

pub(crate) trait SourceResolver {
    fn tag_commit(&self, repository: &str, tag: &str) -> Result<String, OrchestratorError>;

    fn release_asset(
        &self,
        repository: &str,
        tag: &str,
        asset: &str,
    ) -> Result<AssetObservation, OrchestratorError>;
}

pub(crate) fn build_lock(
    config: &PrivateSourcesConfig,
    resolver: &dyn SourceResolver,
) -> Result<DepsLock, OrchestratorError> {
    let asset = |source: &velnor_actions_contract::config::PrivateAssetSource| {
        let commit = resolver.tag_commit(&source.repository, &source.tag)?;
        let observed = resolver.release_asset(&source.repository, &source.tag, &source.asset)?;
        Ok::<_, OrchestratorError>(LockedAsset {
            id: source.id.clone(),
            repository: source.repository.clone(),
            tag: source.tag.clone(),
            commit,
            asset: source.asset.clone(),
            sha256: observed.sha256,
            extract_to: source.extract_to.clone(),
        })
    };
    let lock = DepsLock {
        schema: DEPS_LOCK_SCHEMA,
        maven_bundles: config
            .maven_bundles
            .iter()
            .map(asset)
            .collect::<Result<_, _>>()?,
        release_assets: config
            .release_assets
            .iter()
            .map(asset)
            .collect::<Result<_, _>>()?,
        git_trees: config
            .git_trees
            .iter()
            .map(|source| {
                Ok(LockedGitTree {
                    id: source.id.clone(),
                    repository: source.repository.clone(),
                    tag: source.tag.clone(),
                    commit: resolver.tag_commit(&source.repository, &source.tag)?,
                })
            })
            .collect::<Result<_, OrchestratorError>>()?,
    };
    lock.validate(DEPS_LOCK_PATH).map_err(config_error)?;
    lock.check_matches(config, DEPS_LOCK_PATH)
        .map_err(config_error)?;
    Ok(lock)
}

pub fn render_lock(lock: &DepsLock) -> Result<String, OrchestratorError> {
    let body = toml::to_string(lock).map_err(|err| internal(&format!("deps_lock_encode:{err}")))?;
    Ok(format!("{LOCK_HEADER}{body}"))
}

pub fn read_deps_lock(root: &Path) -> Result<Option<DepsLock>, OrchestratorError> {
    let text = match read_repo_file(root, DEPS_LOCK_PATH, MAX_REPO_FILE_BYTES)? {
        RepoRead::Absent => return Ok(None),
        RepoRead::Text(text) => text,
    };
    let lock: DepsLock = toml::from_str(&text).map_err(|err| {
        config_error(velnor_actions_contract::ContractError::map_decode_error(
            DEPS_LOCK_PATH,
            &err.to_string(),
        ))
    })?;
    lock.validate(DEPS_LOCK_PATH).map_err(config_error)?;
    Ok(Some(lock))
}

pub fn lock_private_sources(root: &Path) -> Result<String, OrchestratorError> {
    let config = load_config(root)?;
    let Some(private) = config.private_sources.as_ref() else {
        return Err(OrchestratorError::config(
            ".velnor/config.toml",
            "private_sources",
            "missing_private_sources",
        ));
    };
    let resolver = GhResolver {
        catalog: ToolCatalog::pinned(),
    };
    let text = render_lock(&build_lock(private, &resolver)?)?;
    write_lock(root, &text)?;
    Ok(text)
}

fn write_lock(root: &Path, text: &str) -> Result<(), OrchestratorError> {
    write_repo_file(root, DEPS_LOCK_PATH, text)
}

pub(crate) fn write_repo_file(root: &Path, rel: &str, text: &str) -> Result<(), OrchestratorError> {
    let path = root.join(rel);
    let directory = path
        .parent()
        .ok_or_else(|| OrchestratorError::io(path.display().to_string(), "no_parent"))?;
    let io =
        |err: std::io::Error| OrchestratorError::io(path.display().to_string(), err.to_string());
    let mut staged = tempfile::NamedTempFile::new_in(directory).map_err(io)?;
    std::io::Write::write_all(&mut staged, text.as_bytes()).map_err(io)?;
    staged.persist(&path).map_err(|err| io(err.error))?;
    Ok(())
}

struct GhResolver {
    catalog: ToolCatalog,
}

impl GhResolver {
    fn api(&self, route: &str, accept: &str, limit: usize) -> Result<Vec<u8>, OrchestratorError> {
        if route.is_empty() || route.starts_with('/') || route.contains("..") {
            return Err(internal("deps_lock_route_invalid"));
        }
        let args = vec![
            OsString::from("api"),
            OsString::from("-H"),
            OsString::from(format!("Accept: {accept}")),
            OsString::from(route),
        ];
        let exec = PinnedToolExec::new(vec![PinnedTool::Gh], OsStr::new("gh"), args)
            .map_err(|_| internal("deps_lock_gh_unavailable"))?;
        let output = exec
            .command(&self.catalog)
            .and_then(|command| command.run_bounded(limit, API_TIMEOUT))
            .map_err(|_| internal("deps_lock_api_unavailable"))?;
        if !output.success {
            return Err(internal(&format!("deps_lock_api_failed:{route}")));
        }
        Ok(output.stdout)
    }
}

impl SourceResolver for GhResolver {
    fn tag_commit(&self, repository: &str, tag: &str) -> Result<String, OrchestratorError> {
        let route = format!("repos/{repository}/commits/refs/tags/{}", encode(tag));
        let bytes = self.api(&route, "application/vnd.github+json", API_JSON_BYTES)?;
        parse_commit(&bytes)
    }

    fn release_asset(
        &self,
        repository: &str,
        tag: &str,
        asset: &str,
    ) -> Result<AssetObservation, OrchestratorError> {
        let route = format!("repos/{repository}/releases/tags/{}", encode(tag));
        let bytes = self.api(&route, "application/vnd.github+json", API_JSON_BYTES)?;
        let found = parse_release_asset(&bytes, asset)?;
        if let Some(sha256) = found.sha256 {
            return Ok(AssetObservation { sha256 });
        }
        let route = format!("repos/{repository}/releases/assets/{}", found.id);
        let content = self.api(&route, "application/octet-stream", MAX_ASSET_HASH_BYTES)?;
        Ok(AssetObservation {
            sha256: crate::generator::sha256_hex(&content),
        })
    }
}

#[derive(Debug, PartialEq, Eq)]
pub(crate) struct FoundAsset {
    pub(crate) id: u64,
    pub(crate) sha256: Option<String>,
}

#[derive(Deserialize)]
struct CommitResponse {
    sha: String,
}

#[derive(Deserialize)]
struct ReleaseResponse {
    #[serde(default)]
    draft: bool,
    assets: Vec<AssetResponse>,
}

#[derive(Deserialize)]
struct AssetResponse {
    id: u64,
    name: String,
    state: String,
    digest: Option<String>,
}

pub(crate) fn parse_commit(bytes: &[u8]) -> Result<String, OrchestratorError> {
    let response: CommitResponse =
        serde_json::from_slice(bytes).map_err(|_| internal("deps_lock_commit_json"))?;
    if response.sha.len() == 40
        && response
            .sha
            .bytes()
            .all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
    {
        Ok(response.sha)
    } else {
        Err(internal("deps_lock_commit_sha_invalid"))
    }
}

pub(crate) fn parse_release_asset(
    bytes: &[u8],
    name: &str,
) -> Result<FoundAsset, OrchestratorError> {
    let release: ReleaseResponse =
        serde_json::from_slice(bytes).map_err(|_| internal("deps_lock_release_json"))?;
    if release.draft {
        return Err(internal("deps_lock_release_is_draft"));
    }
    let mut matching = release.assets.iter().filter(|asset| asset.name == name);
    let (Some(asset), None) = (matching.next(), matching.next()) else {
        return Err(internal(&format!("deps_lock_asset_not_unique:{name}")));
    };
    if asset.state != "uploaded" {
        return Err(internal(&format!("deps_lock_asset_not_uploaded:{name}")));
    }
    let sha256 = match asset.digest.as_deref() {
        None => None,
        Some(digest) => {
            let hex = digest
                .strip_prefix("sha256:")
                .filter(|hex| {
                    hex.len() == 64 && hex.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
                })
                .ok_or_else(|| internal("deps_lock_asset_digest_invalid"))?;
            Some(hex.to_owned())
        }
    };
    Ok(FoundAsset {
        id: asset.id,
        sha256,
    })
}

fn encode(segment: &str) -> String {
    let mut out = String::with_capacity(segment.len());
    for byte in segment.bytes() {
        if byte.is_ascii_alphanumeric() || b"-._~/+".contains(&byte) {
            out.push(char::from(byte));
        } else {
            out.push('%');
            out.push(char::from(UPPER_HEX[usize::from(byte >> 4)]));
            out.push(char::from(UPPER_HEX[usize::from(byte & 0x0f)]));
        }
    }
    out
}
