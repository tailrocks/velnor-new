use super::validate::validate_catalog_slice;

#[must_use]
pub fn all_recipes() -> &'static [CacheRecipe] {
    &ALL_RECIPES
}

#[must_use]
pub fn recipes_of(kind: CacheRecipeKind) -> Vec<&'static CacheRecipe> {
    ALL_RECIPES
        .iter()
        .filter(|recipe| recipe.kind == kind)
        .collect()
}

#[must_use]
pub fn lookup_recipe(key: &str) -> Option<&'static CacheRecipe> {
    ALL_RECIPES.iter().find(|recipe| recipe.recipe_key == key)
}

pub fn validate_catalog() -> Result<(), super::kinds::CacheRecipeError> {
    validate_catalog_slice(&ALL_RECIPES)
}

