#[test]
#[ignore = "requires the catalog-qualified Linux checker and Rust toolchain"]
fn qualified_checker_accepts_lockless_baseline_and_rejects_breakage()
-> Result<(), Box<dyn std::error::Error>> {
    let checker = std::env::var_os("VELNOR_TEST_SEMVER_CHECKER").ok_or("checker path missing")?;
    let checker = std::path::PathBuf::from(checker);
    let qualified = velnor_actions_mise::catalog::qualified_cargo_semver_checks("ubuntu-26.04")
        .ok_or("checker catalog missing")?;
    assert_eq!(
        crate::planner::generator::sha256_hex(&std::fs::read(&checker)?),
        qualified.executable_sha256
    );
    let temp = tempfile::tempdir()?;
    let source = temp.path().join("source");
    std::fs::create_dir_all(source.join("src"))?;
    let manifest = "[package]\nname='demo'\nversion='0.1.1'\nedition='2021'\n";
    std::fs::write(source.join("Cargo.toml"), manifest)?;
    let lock = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"demo\"\nversion = \"0.1.1\"\n";
    std::fs::write(source.join("Cargo.lock"), lock)?;
    std::fs::write(source.join("src/lib.rs"), "pub fn stable_api() {}\n")?;
    let mut tar = tar::Builder::new(flate2::write::GzEncoder::new(
        Vec::new(),
        flate2::Compression::default(),
    ));
    for (path, bytes) in [
        (
            "demo-0.1.0/Cargo.toml",
            "[package]\nname='demo'\nversion='0.1.0'\nedition='2021'\n",
        ),
        ("demo-0.1.0/src/lib.rs", "pub fn stable_api() {}\n"),
    ] {
        let mut header = tar::Header::new_gnu();
        header.set_size(bytes.len() as u64);
        header.set_mode(0o644);
        header.set_cksum();
        tar.append_data(&mut header, path, bytes.as_bytes())?;
    }
    let archive = tar.into_inner()?.finish()?;
    let rust = velnor_actions_mise::ToolCatalog::pinned()
        .version(velnor_actions_mise::PinnedTool::Rust)
        .to_owned();
    let git = crate::crate_release_git::ReleaseGit::host_fixture();
    checker::run_check(
        &source,
        &rust,
        "Cargo.toml",
        "demo",
        ("0.1.0", &archive),
        (&[], &checker),
        &git,
    )?;
    assert_eq!(
        std::fs::read_to_string(source.join("Cargo.toml"))?,
        manifest
    );
    assert_eq!(std::fs::read_to_string(source.join("Cargo.lock"))?, lock);
    assert_eq!(
        std::fs::read_to_string(source.join("src/lib.rs"))?,
        "pub fn stable_api() {}\n"
    );
    std::fs::write(source.join("src/lib.rs"), "pub fn different_api() {}\n")?;
    let baseline = temp.path().join("diagnostic-baseline");
    std::fs::create_dir(&baseline)?;
    checker::extract_baseline(&archive, "demo", "0.1.0", &baseline)?;
    let diagnostic_home = temp.path().join("diagnostic-home");
    std::fs::create_dir(&diagnostic_home)?;
    let mut diagnostic = std::process::Command::new(&checker);
    diagnostic
        .env_clear()
        .env("HOME", &diagnostic_home)
        .env("CARGO_HOME", &diagnostic_home)
        .env("CARGO_NET_OFFLINE", "true")
        .env("CARGO", source_cargo_path(&rust, &source)?);
    for item in source_compiler_env(&rust, &git)? {
        let text = item.to_str().ok_or("compiler environment is not UTF-8")?;
        let (name, value) = text.split_once('=').ok_or("invalid compiler environment")?;
        diagnostic.env(name, value);
    }
    let output = diagnostic
        .args(["check-release", "--manifest-path"])
        .arg(source.join("Cargo.toml"))
        .args(["--package", "demo", "--baseline-root"])
        .arg(&baseline)
        .arg("--default-features")
        .current_dir(&source)
        .output()?;
    assert!(!output.status.success());
    assert!(
        String::from_utf8_lossy(&output.stderr).contains("function_missing")
            || String::from_utf8_lossy(&output.stdout).contains("function_missing")
    );
    assert!(
        checker::run_check(
            &source,
            &rust,
            "Cargo.toml",
            "demo",
            ("0.1.0", &archive),
            (&[], &checker),
            &git
        )
        .is_err()
    );
    assert_eq!(std::fs::read_to_string(source.join("Cargo.lock"))?, lock);
    assert_eq!(
        std::fs::read_to_string(source.join("src/lib.rs"))?,
        "pub fn different_api() {}\n"
    );
    Ok(())
}

#[test]
#[ignore = "requires the catalog-qualified Linux checker and Rust toolchain"]
fn qualified_checker_checks_shared_features_and_allows_new_features()
-> Result<(), Box<dyn std::error::Error>> {
    let checker = std::path::PathBuf::from(
        std::env::var_os("VELNOR_TEST_SEMVER_CHECKER").ok_or("checker path missing")?,
    );
    let qualified = velnor_actions_mise::catalog::qualified_cargo_semver_checks("ubuntu-26.04")
        .ok_or("checker catalog missing")?;
    assert_eq!(
        crate::planner::generator::sha256_hex(&std::fs::read(&checker)?),
        qualified.executable_sha256
    );
    let temp = tempfile::tempdir()?;
    let source = temp.path().join("source");
    std::fs::create_dir_all(source.join("src"))?;
    std::fs::write(
        source.join("Cargo.toml"),
        "[package]\nname='demo'\nversion='0.1.1'\nedition='2021'\n[features]\nold=[]\nnew=[]\n",
    )?;
    std::fs::write(
        source.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"demo\"\nversion = \"0.1.1\"\n",
    )?;
    std::fs::write(
        source.join("src/lib.rs"),
        "#[cfg(feature=\"old\")] pub fn stable_api() {}\n",
    )?;
    let mut tar = tar::Builder::new(flate2::write::GzEncoder::new(
        Vec::new(),
        flate2::Compression::default(),
    ));
    for (path, bytes) in [
        (
            "demo-0.1.0/Cargo.toml",
            "[package]\nname='demo'\nversion='0.1.0'\nedition='2021'\n[features]\nold=[]\n",
        ),
        (
            "demo-0.1.0/src/lib.rs",
            "#[cfg(feature=\"old\")] pub fn stable_api() {}\n",
        ),
    ] {
        let mut header = tar::Header::new_gnu();
        header.set_size(bytes.len() as u64);
        header.set_mode(0o644);
        header.set_cksum();
        tar.append_data(&mut header, path, bytes.as_bytes())?;
    }
    let archive = tar.into_inner()?.finish()?;
    let rust = velnor_actions_mise::ToolCatalog::pinned()
        .version(velnor_actions_mise::PinnedTool::Rust)
        .to_owned();
    let git = crate::crate_release_git::ReleaseGit::host_fixture();
    let features = vec!["old".to_owned(), "new".to_owned()];
    checker::run_check(
        &source,
        &rust,
        "Cargo.toml",
        "demo",
        ("0.1.0", &archive),
        (&features, &checker),
        &git,
    )?;
    std::fs::write(source.join("src/lib.rs"), "pub fn unrelated() {}\n")?;
    assert!(
        checker::run_check(
            &source,
            &rust,
            "Cargo.toml",
            "demo",
            ("0.1.0", &archive),
            (&features, &checker),
            &git
        )
        .is_err()
    );
    Ok(())
}
