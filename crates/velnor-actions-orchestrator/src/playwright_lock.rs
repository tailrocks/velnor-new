//! `.velnor/playwright.lock` on disk: read, render, and what the configured
//! members need (hard decision 6). Pure file and text work; the network side
//! lives in `playwright_resolve.rs`.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::io::Read;
use std::path::Path;

use sha2::{Digest, Sha256};
use velnor_actions_contract::config::BunBrowser;
use velnor_actions_contract::config::playwright_lock::{PLAYWRIGHT_LOCK_PATH, PlaywrightLock};

use crate::OrchestratorError;
use crate::config::config_error;
use crate::internal::internal;
use crate::safe_read::{MAX_REPO_FILE_BYTES, RepoRead, read_repo_file};

const LOCK_HEADER: &str = "# Generated by `velnor-actions playwright lock`. Do not edit by hand.\n";

/// One `playwright-core` version to resolve, with the browsers its members need.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct CoreRequest {
    pub(crate) version: String,
    /// Integrity recorded in `bun.lock`.
    pub(crate) integrity: String,
    pub(crate) browsers: BTreeSet<BunBrowser>,
}

/// Lowercase hex SHA-256 and size of a file, read in bounded chunks.
///
/// # Errors
/// Fails on an unreadable file or one larger than `limit`.
pub(crate) fn hash_file(path: &Path, limit: u64) -> Result<(String, u64), OrchestratorError> {
    let io =
        |err: std::io::Error| OrchestratorError::io(path.display().to_string(), err.to_string());
    let mut file = fs::File::open(path).map_err(io)?;
    let mut hasher = Sha256::new();
    let mut buffer = vec![0_u8; 1 << 20];
    let mut total = 0_u64;
    loop {
        let read = file.read(&mut buffer).map_err(io)?;
        if read == 0 {
            break;
        }
        total += read as u64;
        if total > limit {
            return Err(internal("playwright_archive_too_large"));
        }
        hasher.update(&buffer[..read]);
    }
    Ok((hex(&hasher.finalize()), total))
}

pub(crate) fn hex(bytes: &[u8]) -> String {
    const DIGITS: &[u8; 16] = b"0123456789abcdef";
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push(char::from(DIGITS[usize::from(byte >> 4)]));
        out.push(char::from(DIGITS[usize::from(byte & 0x0f)]));
    }
    out
}

/// Deterministic lock document.
///
/// # Errors
/// Fails only if serialization does.
pub fn render_playwright_lock(lock: &PlaywrightLock) -> Result<String, OrchestratorError> {
    let body =
        toml::to_string(lock).map_err(|err| internal(&format!("playwright_lock_encode:{err}")))?;
    Ok(format!("{LOCK_HEADER}{body}"))
}

/// Read and validate `.velnor/playwright.lock`; absent returns `None`.
///
/// # Errors
/// Rejects symlinks, oversize files, malformed TOML and invalid pins.
pub fn read_playwright_lock(root: &Path) -> Result<Option<PlaywrightLock>, OrchestratorError> {
    let text = match read_repo_file(root, PLAYWRIGHT_LOCK_PATH, MAX_REPO_FILE_BYTES)? {
        RepoRead::Absent => return Ok(None),
        RepoRead::Text(text) => text,
    };
    let lock: PlaywrightLock = toml::from_str(&text).map_err(|err| {
        config_error(velnor_actions_contract::ContractError::map_decode_error(
            PLAYWRIGHT_LOCK_PATH,
            &err.to_string(),
        ))
    })?;
    lock.validate(PLAYWRIGHT_LOCK_PATH).map_err(config_error)?;
    Ok(Some(lock))
}

/// Every browser a member's jobs install: its own `browsers` and those of
/// each of its suites (a suite job installs only its own; the lock pins all).
pub(crate) fn member_browsers(
    config: Option<&velnor_actions_contract::config::BunMemberConfig>,
) -> BTreeSet<BunBrowser> {
    config
        .into_iter()
        .flat_map(|member| {
            member.browsers.iter().chain(
                member
                    .suites
                    .values()
                    .flat_map(|suite| suite.browsers.iter()),
            )
        })
        .copied()
        .collect()
}

/// What the configured members need: one request per `playwright-core` version.
///
/// # Errors
/// `bun_playwright_missing:<member>` for a member with browsers and no
/// Playwright, and `bun_playwright_core_mismatch:<member>` when the lock's
/// `playwright-core` is not the member's Playwright version.
pub(crate) fn core_requests(
    bun: &velnor_actions_contract::config::BunStackConfig,
    inventory: &crate::workflow_task_jobs::bun_inventory::BunInventory,
) -> Result<Vec<CoreRequest>, OrchestratorError> {
    let mut requests: BTreeMap<String, CoreRequest> = BTreeMap::new();
    for root in &inventory.roots {
        for member in &root.workspace.members {
            let browsers = member_browsers(bun.members.get(&member.name));
            if browsers.is_empty() {
                continue;
            }
            let failure = |problem: &str| {
                OrchestratorError::config(
                    crate::config::CONFIG_REL,
                    "stacks.bun.members.browsers",
                    format!("{problem}:{}", member.name),
                )
            };
            let version = member
                .playwright
                .as_ref()
                .ok_or_else(|| failure("bun_playwright_missing"))?;
            let core = root
                .workspace
                .playwright_core
                .as_ref()
                .filter(|core| &core.version == version)
                .ok_or_else(|| failure("bun_playwright_core_mismatch"))?;
            let request = requests
                .entry(core.version.clone())
                .or_insert_with(|| CoreRequest {
                    version: core.version.clone(),
                    integrity: core.integrity.clone(),
                    browsers: BTreeSet::new(),
                });
            if request.integrity != core.integrity {
                return Err(failure("bun_playwright_core_mismatch"));
            }
            request.browsers.extend(browsers);
        }
    }
    Ok(requests.into_values().collect())
}

