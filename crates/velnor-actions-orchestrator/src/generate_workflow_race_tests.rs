use super::{exchange_directories, publish_existing_with, stage_root::StageRoot};

#[test]
fn handwritten_workflow_created_immediately_before_exchange_survives() -> Result<(), Box<dyn std::error::Error>> {
    let root = tempfile::tempdir()?;
    let target = root.path().join(".github");
    std::fs::create_dir_all(target.join("workflows"))?;
    std::fs::write(target.join("workflows/old.yml"), "# Generated by Velnor Actions 0.1.0\n")?;
    let staging = StageRoot::open(root.path())?;
    let retired = staging.validate_target(&target)?.ok_or("missing target")?;
    let staged = staging.spare().to_path_buf();
    std::fs::create_dir_all(staged.join("workflows"))?;
    std::fs::write(staged.join("workflows/new.yml"), "generated\n")?;
    let path = target.join("workflows/late.yml");
    let result = publish_existing_with(&staging, &target, retired, &staged, |from, to| {
        std::fs::write(&path, "must survive\n")?;
        exchange_directories(from, to)
    });
    assert!(result.is_err());
    assert_eq!(std::fs::read_to_string(staged.join("workflows/late.yml"))?, "must survive\n");
    assert_eq!(std::fs::read_to_string(staged.join("workflows/old.yml"))?, "# Generated by Velnor Actions 0.1.0\n");
    assert_eq!(std::fs::read_to_string(target.join("workflows/new.yml"))?, "generated\n");
    let error = result.expect_err("concurrent workflow must fail").to_string();
    assert!(error.contains(&target.display().to_string()));
    assert!(error.contains(&staged.display().to_string()));
    Ok(())
}

#[test]
fn replaced_published_root_is_never_exchanged_back() -> Result<(), Box<dyn std::error::Error>> {
    let root = tempfile::tempdir()?;
    let target = root.path().join(".github");
    std::fs::create_dir_all(target.join("workflows"))?;
    std::fs::write(target.join("workflows/old.yml"), "# Generated by Velnor Actions 0.1.0\n")?;
    let staging = StageRoot::open(root.path())?;
    let retired = staging.validate_target(&target)?.ok_or("missing target")?;
    let staged = staging.spare().to_path_buf();
    std::fs::create_dir_all(staged.join("workflows"))?;
    std::fs::write(staged.join("workflows/new.yml"), "generated\n")?;
    let displaced = root.path().join("displaced");
    let result = publish_existing_with(&staging, &target, retired, &staged, |from, to| {
        exchange_directories(from, to)?;
        std::fs::rename(to, &displaced)?;
        std::fs::create_dir(to)?;
        std::fs::write(to.join("other"), "unrelated\n")?;
        Ok(())
    });
    assert!(result.is_err());
    assert_eq!(std::fs::read_to_string(target.join("other"))?, "unrelated\n");
    assert_eq!(std::fs::read_to_string(staged.join("workflows/old.yml"))?, "# Generated by Velnor Actions 0.1.0\n");
    let recovered = StageRoot::open(root.path())?;
    let retained = recovered.recovered().ok_or("missing recovery path")?;
    assert_eq!(std::fs::read_to_string(retained.join("workflows/old.yml"))?, "# Generated by Velnor Actions 0.1.0\n");
    Ok(())
}

#[test]
fn marked_retirement_succeeds_and_spare_is_reusable() -> Result<(), Box<dyn std::error::Error>> {
    let root = tempfile::tempdir()?;
    let target = root.path().join(".github");
    std::fs::create_dir_all(target.join("workflows"))?;
    std::fs::write(target.join("workflows/old.yml"), "# Generated by Velnor Actions 0.1.0\n")?;
    let staging = StageRoot::open(root.path())?;
    let retired = staging.validate_target(&target)?.ok_or("missing target")?;
    let staged = staging.spare().to_path_buf();
    std::fs::create_dir_all(staged.join("workflows"))?;
    std::fs::write(staged.join("workflows/new.yml"), "generated\n")?;
    let warnings = publish_existing_with(&staging, &target, retired, &staged, exchange_directories)?;
    assert_eq!(warnings.len(), 1);
    assert!(warnings[0].starts_with("retired_tree_retained:"));
    assert!(!target.join("workflows/old.yml").exists());
    assert_eq!(std::fs::read_to_string(target.join("workflows/new.yml"))?, "generated\n");
    assert!(StageRoot::open(root.path()).is_ok());
    Ok(())
}

#[test]
fn late_write_through_old_directory_handle_is_retained_across_reopen() -> Result<(), Box<dyn std::error::Error>> {
    use std::io::Write as _;
    use std::os::unix::fs::PermissionsExt as _;
    let root = tempfile::tempdir()?;
    let target = root.path().join(".github");
    std::fs::create_dir_all(target.join("workflows"))?;
    std::fs::write(target.join("workflows/old.yml"), "# Generated by Velnor Actions 0.1.0\n")?;
    let old_workflows = std::fs::File::open(target.join("workflows"))?;
    let staging = StageRoot::open(root.path())?;
    let retired = staging.validate_target(&target)?.ok_or("missing target")?;
    let staged = staging.spare().to_path_buf();
    std::fs::create_dir_all(staged.join("workflows"))?;
    std::fs::write(staged.join("workflows/new.yml"), "generated\n")?;
    let warnings = publish_existing_with(&staging, &target, retired, &staged, exchange_directories)?;
    let retained = warnings.first().and_then(|w| w.strip_prefix("retired_tree_retained:")).ok_or("missing retained path")?;
    let fd = rustix::fs::openat(&old_workflows, "late.yml", rustix::fs::OFlags::WRONLY | rustix::fs::OFlags::CREATE | rustix::fs::OFlags::EXCL, rustix::fs::Mode::RUSR | rustix::fs::Mode::WUSR)?;
    std::fs::File::from(fd).write_all(b"late data\n")?;
    let reopened = StageRoot::open(root.path())?;
    assert_eq!(std::fs::read_to_string(std::path::Path::new(retained).join("workflows/late.yml"))?, "late data\n");
    assert!(reopened.spare().read_dir()?.next().is_none());
    assert_eq!(std::fs::metadata(reopened.spare())?.permissions().mode() & 0o777, 0o700);
    Ok(())
}

#[test]
fn crash_after_exchange_with_empty_old_tree_retains_late_fd_writes() -> Result<(), Box<dyn std::error::Error>> {
    use std::io::Write as _;
    let root = tempfile::tempdir()?;
    let target = root.path().join(".github");
    std::fs::create_dir(&target)?;
    let old = std::fs::File::open(&target)?;
    let staging = StageRoot::open(root.path())?;
    let staged = staging.spare().to_path_buf();
    std::fs::write(staged.join("generated"), "new\n")?;
    exchange_directories(&staged, &target)?;
    drop(staging);
    let recovered = StageRoot::open(root.path())?;
    let retained = recovered.recovered().ok_or("missing recovered path")?;
    let fd = rustix::fs::openat(&old, "late.yml", rustix::fs::OFlags::WRONLY | rustix::fs::OFlags::CREATE | rustix::fs::OFlags::EXCL, rustix::fs::Mode::RUSR | rustix::fs::Mode::WUSR)?;
    std::fs::File::from(fd).write_all(b"after crash\n")?;
    assert_eq!(std::fs::read_to_string(retained.join("late.yml"))?, "after crash\n");
    Ok(())
}

#[test]
fn restart_after_spare_rename_recreates_private_spare() -> Result<(), Box<dyn std::error::Error>> {
    use std::os::unix::fs::PermissionsExt as _;
    let root = tempfile::tempdir()?;
    let stage = StageRoot::open(root.path())?;
    let original = stage.spare().to_path_buf();
    std::fs::write(original.join("keep"), "data\n")?;
    let retained = original.parent().ok_or("container")?.join("interrupted-retained");
    std::fs::rename(&original, &retained)?;
    drop(stage);
    let recovered = StageRoot::open(root.path())?;
    assert_eq!(std::fs::read_to_string(retained.join("keep"))?, "data\n");
    assert_eq!(std::fs::metadata(recovered.spare())?.permissions().mode() & 0o777, 0o700);
    assert_eq!(std::fs::metadata(original.parent().ok_or("container")?)?.permissions().mode() & 0o777, 0o700);
    Ok(())
}
