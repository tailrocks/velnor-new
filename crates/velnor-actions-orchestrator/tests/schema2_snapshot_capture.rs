pub(super) fn capture_if_requested(tree: &RenderedTree) -> Result<(), Box<dyn Error>> {
    if std::env::var_os("VELNOR_UPDATE_GOLDENS").as_deref() != Some(OsStr::new("1")) {
        return Ok(());
    }

    let header = format!(
        "# Generated by Velnor Actions {}; edit .velnor/config.toml and regenerate.\n",
        env!("CARGO_PKG_VERSION")
    );
    let snapshot_root = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/snapshots");
    for (rendered_path, snapshot_path, previous_snapshot) in SNAPSHOTS {
        let rendered = tree
            .get(rendered_path)
            .ok_or_else(|| format!("missing rendered snapshot source {rendered_path}"))?;
        let body = rendered
            .strip_prefix(&header)
            .ok_or_else(|| format!("generated header mismatch for {rendered_path}"))?;
        let contents = if previous_snapshot.contains("@COMPILED_RELEASE_VERSION@") {
            body.replace(env!("CARGO_PKG_VERSION"), "@COMPILED_RELEASE_VERSION@")
        } else {
            body.to_owned()
        };
        fs::write(snapshot_root.join(snapshot_path), contents)?;
    }
    Ok(())
}
