//! Generated `.github/dco.yml`: config-driven, drift-checkable, marker-owned.

use std::fs;

use tempfile::TempDir;
use velnor_actions_orchestrator::{
    GenerateOptions, OrchestratorError, generate, plan_text_checked, prepare,
};

use crate::impl_common::{TestResult, make_repo};

const DCO_CONFIG: &str = "schema = 1\n[workflow]\nname = \"CI\"\ndefault_branch = \"testmain\"\n[dco]\nallow_remediation_commits = { individual = true, third_party = true }\n";
const NO_DCO_CONFIG: &str =
    "schema = 1\n[workflow]\nname = \"CI\"\ndefault_branch = \"testmain\"\n";

fn version_marker() -> String {
    format!(
        "# Generated by Velnor Actions {}; edit .velnor/config.toml and regenerate.\n",
        env!("CARGO_PKG_VERSION")
    )
}

fn expected() -> String {
    format!(
        "{}allowRemediationCommits:\n  individual: true\n  thirdParty: true\n",
        version_marker()
    )
}

#[test]
fn configured_dco_is_generated_in_place_and_in_preview_identically() -> TestResult {
    let repo = make_repo(DCO_CONFIG)?;
    let root = repo.path();
    let prep = prepare(root)?;
    assert!(
        plan_text_checked(&prep)?.contains(".github/dco.yml"),
        "plan lists the generated file"
    );
    let preview_parent = TempDir::new()?;
    let preview = preview_parent.path().join("preview");
    generate(
        &prep,
        &GenerateOptions {
            output_dir: Some(preview.clone()),
        },
    )?;
    generate(&prep, &GenerateOptions::default())?;
    assert_eq!(
        fs::read_to_string(root.join(".github/dco.yml"))?,
        expected()
    );
    assert_eq!(
        fs::read(preview.join(".github/dco.yml"))?,
        fs::read(root.join(".github/dco.yml"))?,
        "the drift check compares preview and committed bytes"
    );
    // Regenerating over its own marked output is stable.
    generate(&prep, &GenerateOptions::default())?;
    assert_eq!(
        fs::read_to_string(root.join(".github/dco.yml"))?,
        expected()
    );
    Ok(())
}

#[test]
fn drifted_generated_dco_is_replaced() -> TestResult {
    let repo = make_repo(DCO_CONFIG)?;
    let root = repo.path();
    let prep = prepare(root)?;
    generate(&prep, &GenerateOptions::default())?;
    let path = root.join(".github/dco.yml");
    fs::write(
        &path,
        format!(
            "{}allowRemediationCommits:\n  individual: false\n",
            version_marker()
        ),
    )?;
    generate(&prep, &GenerateOptions::default())?;
    assert_eq!(fs::read_to_string(&path)?, expected());
    Ok(())
}

#[test]
fn hand_written_dco_collides_with_configured_generation() -> TestResult {
    let repo = make_repo(DCO_CONFIG)?;
    let root = repo.path();
    fs::create_dir_all(root.join(".github"))?;
    let hand = "require:\n  members: false\n";
    fs::write(root.join(".github/dco.yml"), hand)?;
    let prep = prepare(root)?;
    let err = generate(&prep, &GenerateOptions::default()).expect_err("hand-written file");
    assert!(
        matches!(err, OrchestratorError::OverwriteRefused { .. }),
        "{err}"
    );
    assert_eq!(fs::read_to_string(root.join(".github/dco.yml"))?, hand);
    Ok(())
}

#[test]
fn absent_dco_config_preserves_hand_written_file_and_emits_none() -> TestResult {
    let repo = make_repo(NO_DCO_CONFIG)?;
    let root = repo.path();
    let prep = prepare(root)?;
    generate(&prep, &GenerateOptions::default())?;
    assert!(!root.join(".github/dco.yml").exists(), "no config, no file");
    assert!(!plan_text_checked(&prep)?.contains("dco.yml"));
    let hand = "require:\n  members: false\n";
    fs::write(root.join(".github/dco.yml"), hand)?;
    generate(&prep, &GenerateOptions::default())?;
    assert_eq!(fs::read_to_string(root.join(".github/dco.yml"))?, hand);
    Ok(())
}

#[test]
fn removing_the_dco_table_retires_the_generated_file() -> TestResult {
    let repo = make_repo(DCO_CONFIG)?;
    let root = repo.path();
    generate(&prepare(root)?, &GenerateOptions::default())?;
    assert!(root.join(".github/dco.yml").is_file());
    fs::write(root.join(".velnor/config.toml"), NO_DCO_CONFIG)?;
    generate(&prepare(root)?, &GenerateOptions::default())?;
    assert!(!root.join(".github/dco.yml").exists());
    Ok(())
}

#[test]
fn invalid_dco_tables_fail_before_any_write() -> TestResult {
    for body in [
        "[dco]\n",
        "[dco]\nallow_remediation_commits = { third_party = true }\n",
        "[dco]\nallow_remediation_commits = { individual = false, third_party = true }\n",
        "[dco]\nunknown = true\n",
    ] {
        let repo = make_repo(&format!("{NO_DCO_CONFIG}{body}"))?;
        assert!(prepare(repo.path()).is_err(), "{body}");
        assert!(!repo.path().join(".github").exists(), "{body}");
    }
    Ok(())
}
