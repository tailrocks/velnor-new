use super::workflow_configuration_fixture::make_repo;
use std::{error::Error, fs, path::Path, path::PathBuf};
use velnor_actions_orchestrator::{
    GenerateOptions, OrchestratorError, generate, prepare, render_staged_tree,
};
use velnor_actions_workflow_renderer::render::WORKFLOW_PATH;

const CONFIG: &str = "schema = 1\n[workflow]\nname = \"CI\"\ndefault_branch = \"testmain\"\n[stacks]\nignore = [\"rust\"]\n[github]\nunmanaged = \"deny\"\n";
const MARKED: &str = "# Generated by velnor-gen. Change .velnor/rust-ci.toml and run `velnor-gen generate`.\nname: Rust CI\n";
const MARKED_PATH: &str = ".github/workflows/rust-ci.yml";

fn place(root: &Path, path: &str, contents: &str) -> Result<(), Box<dyn Error>> {
    let path = root.join(path);
    fs::create_dir_all(path.parent().ok_or("no parent")?)?;
    fs::write(path, contents)?;
    Ok(())
}

fn preview(root: &Path) -> Result<(tempfile::TempDir, PathBuf), Box<dyn Error>> {
    let output = tempfile::tempdir()?;
    let destination = output.path().join("preview");
    generate(
        &prepare(root)?,
        &GenerateOptions {
            output_dir: Some(destination.clone()),
        },
    )?;
    Ok((output, destination))
}

#[test]
fn generator_owned_leaves_a_velnor_gen_workflow() -> Result<(), Box<dyn Error>> {
    let repository = make_repo(CONFIG)?;
    let root = repository.path();
    place(root, MARKED_PATH, MARKED)?;
    let (_output, destination) = preview(root)?;
    assert_eq!(fs::read_to_string(destination.join(MARKED_PATH))?, MARKED);
    generate(&prepare(root)?, &GenerateOptions::default())?;
    assert_eq!(fs::read_to_string(root.join(MARKED_PATH))?, MARKED);
    assert!(root.join(WORKFLOW_PATH).is_file());
    Ok(())
}

#[test]
fn generator_owned_retires_an_unmarked_workflow() -> Result<(), Box<dyn Error>> {
    let repository = make_repo(CONFIG)?;
    let root = repository.path();
    let strays = [
        (".github/workflows/stray.yml", "name: Stray\n"),
        (
            ".github/workflows/late.yml",
            "name: Late\n# Generated by velnor-gen.\n",
        ),
        (
            ".github/workflows/fork.yml",
            "# Generated by velnor-gen.fork\nname: Fork\n",
        ),
    ];
    for (path, contents) in strays {
        place(root, path, contents)?;
    }
    let (_output, destination) = preview(root)?;
    generate(&prepare(root)?, &GenerateOptions::default())?;
    for (path, _) in strays {
        assert!(!destination.join(path).exists(), "{path} copied to preview");
        assert!(!root.join(path).exists(), "{path} kept in place");
    }
    Ok(())
}

#[test]
fn generator_owned_refuses_to_overwrite_a_velnor_gen_workflow() -> Result<(), Box<dyn Error>> {
    let repository = make_repo(CONFIG)?;
    let root = repository.path();
    assert!(
        render_staged_tree(&prepare(root)?)?
            .get(WORKFLOW_PATH)
            .is_some()
    );
    place(root, WORKFLOW_PATH, MARKED)?;
    let output = tempfile::tempdir()?;
    for options in [
        GenerateOptions {
            output_dir: Some(output.path().join("preview")),
        },
        GenerateOptions::default(),
    ] {
        let refused = generate(&prepare(root)?, &options);
        assert!(
            matches!(&refused, Err(OrchestratorError::OverwriteRefused { path }) if path.ends_with("workflows/ci.yml")),
            "{refused:?}"
        );
        assert_eq!(fs::read_to_string(root.join(WORKFLOW_PATH))?, MARKED);
    }
    assert!(!output.path().join("preview/.github").exists());
    Ok(())
}
