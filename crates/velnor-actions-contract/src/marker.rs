pub const MARKER_PREFIX: &str = "# Generated by Velnor Actions ";

pub const OLD_MARKER_PREFIX: &str = "# Generated by velnor-actions ";

#[must_use]
pub fn is_generated_marker_line(first: &str) -> bool {
    first.starts_with(MARKER_PREFIX) || first.starts_with(OLD_MARKER_PREFIX)
}
