//! A job with no `cache-mode` key gets GitHub's default, and on a trusted trigger that is
//! `write`. So the renderer writes `cache-mode: read` on every job that does not declare a mode,
//! and a write only comes from a declaration (`cache_mode = "write"` in `.velnor/workflows.toml`).

use std::collections::BTreeSet;
use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};

use velnor_gen::expected_with_notes;

use crate::golden::{load, sample_dirs, samples};
use crate::yaml_tree::parse;

type TestResult = Result<(), Box<dyn Error>>;

const GENERATED: &str = "# Generated by velnor-gen.";

/// The ids of the jobs that declare a mode that writes, from one `workflows.toml`.
fn declared_writers(config: &str) -> Result<BTreeSet<String>, Box<dyn Error>> {
    let table: toml::Table = config.parse()?;
    let mut writers = BTreeSet::new();
    for workflow in table
        .get("workflow")
        .and_then(toml::Value::as_array)
        .into_iter()
        .flatten()
    {
        for (key, suffixes) in [("job", &[""][..]), ("case", &["-hosted", "-scale-set"][..])] {
            for job in workflow
                .get(key)
                .and_then(toml::Value::as_array)
                .into_iter()
                .flatten()
            {
                let mode = job.get("cache_mode").and_then(toml::Value::as_str);
                let id = job.get("id").and_then(toml::Value::as_str);
                if let (Some("write" | "write-only"), Some(id)) = (mode, id) {
                    writers.extend(suffixes.iter().map(|suffix| format!("{id}{suffix}")));
                }
            }
        }
    }
    Ok(writers)
}

/// What is wrong with the `cache-mode` of each job of one rendered workflow.
fn violations(text: &str, writers: &BTreeSet<String>) -> Result<Vec<String>, Box<dyn Error>> {
    let tree = parse(text)?;
    let mut found = Vec::new();
    let jobs = tree.get("jobs").ok_or("no jobs")?;
    for id in jobs.keys() {
        let job = jobs.get(id).ok_or("job vanished")?;
        let mode = job.get("cache-mode").and_then(crate::yaml_tree::Node::text);
        match mode {
            None if job.get("uses").is_none() => found.push(format!("{id}: no cache-mode")),
            Some("write" | "write-only") if !writers.contains(id) => {
                found.push(format!("{id}: writes the cache without declaring it"));
            }
            _ => {}
        }
    }
    Ok(found)
}

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn config_at(dir: &Path) -> Result<BTreeSet<String>, Box<dyn Error>> {
    match fs::read_to_string(dir.join(".velnor/workflows.toml")) {
        Ok(config) => declared_writers(&config),
        Err(_) => Ok(BTreeSet::new()),
    }
}

/// One generated workflow: where it came from, its text, and the writers its repository declares.
struct Generated {
    label: String,
    text: String,
    writers: BTreeSet<String>,
}

/// The repository's committed generated workflows, and every sample rendered from its view. A
/// sample that no longer renders is the golden test's failure, so it is not counted here.
fn generated() -> Result<Vec<Generated>, Box<dyn Error>> {
    let mut files = Vec::new();
    let repo = root();
    let writers = config_at(&repo)?;
    for entry in fs::read_dir(repo.join(".github/workflows"))? {
        let path = entry?.path();
        let text = fs::read_to_string(&path)?;
        if text.starts_with(GENERATED) {
            let label = path.display().to_string();
            files.push(Generated {
                label,
                text,
                writers: writers.clone(),
            });
        }
    }
    for sample in sample_dirs(&samples())? {
        let Ok((rendered, _)) = expected_with_notes(&load(&sample)?) else {
            continue;
        };
        let writers = config_at(&sample.join("view"))?;
        for (path, text) in rendered {
            if path.as_str().starts_with(".github/workflows/") {
                let label = format!("{}:{path}", sample.display());
                files.push(Generated {
                    label,
                    text,
                    writers: writers.clone(),
                });
            }
        }
    }
    Ok(files)
}

#[test]
fn no_generated_job_leaves_the_cache_mode_to_the_default() -> TestResult {
    let files = generated()?;
    assert!(files.len() > 30, "{}", files.len());
    for file in files {
        let found = violations(&file.text, &file.writers)?;
        assert!(found.is_empty(), "{}: {found:?}", file.label);
    }
    Ok(())
}

#[test]
fn the_scan_catches_a_missing_mode_and_an_undeclared_write() -> TestResult {
    let none = BTreeSet::new();
    let declared = BTreeSet::from(["save".to_owned()]);
    let plain = "jobs:\n  a:\n    cache-mode: read\n    runs-on: x\n  save:\n    cache-mode: write\n    runs-on: x\n  call:\n    uses: ./w.yml\n";
    assert_eq!(violations(plain, &declared)?, Vec::<String>::new());
    assert_eq!(
        violations(plain, &none)?,
        ["save: writes the cache without declaring it"]
    );
    let bare = plain.replace("    cache-mode: read\n", "");
    assert_eq!(violations(&bare, &declared)?, ["a: no cache-mode"]);
    Ok(())
}

#[test]
fn the_writers_are_the_declared_ones() -> TestResult {
    let config = "[[workflow]]\nfile = \"q\"\n[[workflow.job]]\nid = \"w\"\ncache_mode = \"write\"\n[[workflow.job]]\nid = \"r\"\ncache_mode = \"read\"\n[[workflow.job]]\nid = \"n\"\n[[workflow.case]]\nid = \"c\"\ncache_mode = \"write\"\n";
    let expected = ["w", "c-hosted", "c-scale-set"].map(str::to_owned);
    assert_eq!(declared_writers(config)?, BTreeSet::from(expected));
    let repo = config_at(&root())?;
    assert_eq!(repo.len(), 4, "{repo:?}");
    Ok(())
}
