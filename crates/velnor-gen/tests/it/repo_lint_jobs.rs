use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};

use crate::facts::TestResult;
use crate::yaml_tree::document;

const GENERATED: &str = "# Generated by velnor-gen.";
const LINT_AND_POLICY_JOBS: &[&str] = &["alint", "jactionlint", "cargo-deny", "cargo-machete"];

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn workflows() -> Result<Vec<(String, String)>, Box<dyn Error>> {
    let mut found = Vec::new();
    for entry in fs::read_dir(root().join(".github/workflows"))? {
        let path = entry?.path();
        if path.extension().is_some_and(|ext| ext == "yml") {
            let name = path
                .file_name()
                .and_then(|name| name.to_str())
                .ok_or("a workflow name is not UTF-8")?
                .to_owned();
            found.push((name, fs::read_to_string(&path)?));
        }
    }
    Ok(found)
}

#[test]
fn the_required_check_of_the_repository_waits_for_every_lint_and_the_policy_lane() -> TestResult {
    let text = fs::read_to_string(root().join(".github/workflows/rust-ci.yml"))?;
    let needs: Vec<String> = document(&text)?["jobs"]["required"]["needs"]
        .as_array()
        .ok_or("the required job has no needs")?
        .iter()
        .filter_map(|need| need.as_str().map(str::to_owned))
        .collect();
    for job in [
        "lint-alint",
        "lint-jactionlint",
        "lint-generator-samples",
        "lint-parity-verify-candidate",
        "policy",
    ] {
        assert!(
            needs.iter().any(|need| need == job),
            "{job} not in {needs:?}"
        );
    }
    Ok(())
}

#[test]
fn no_hand_written_workflow_runs_a_lint_or_dependency_policy_job() -> TestResult {
    for (name, text) in workflows()? {
        if text.starts_with(GENERATED) {
            continue;
        }
        let tree = document(&text)?;
        let jobs = tree["jobs"].as_object().into_iter().flatten();
        for (id, job) in jobs {
            let title = job["name"].as_str().unwrap_or_default().to_lowercase();
            let title = title.replace(' ', "-");
            for lint in LINT_AND_POLICY_JOBS.iter().copied() {
                assert!(
                    id != lint && title != lint,
                    "{name} runs {lint} by hand as job {id}: declare it in .velnor/rust-ci.toml so Required covers it"
                );
            }
        }
    }
    Ok(())
}
