//! Latest Mise lockfile structures and repeated tool entries.
use super::*;

#[test]
fn parses_single_quoted_literal_strings_and_repeated_tool_entries() -> Result<(), String> {
    let catalog = catalog();
    let rust_ver = catalog.version(PinnedTool::Rust);
    let actionlint_ver = catalog.version(PinnedTool::Actionlint);
    let text = format!(
        r#"# @generated - this file is auto-generated by mise

lockfile_version = 3

[[tools."github:boltffi/boltffi"]]
version = "0.1.8"
backend = "github:boltffi/boltffi"
specifiers = ["0.1.8"]

[tools."github:boltffi/boltffi".options]
bin = "boltffi"
matching_regex = '^boltffi-(darwin-aarch64|darwin-x86_64|linux-aarch64(-musl)?|linux-x86_64(-musl)?|windows-arm64|windows-x86_64)\.(tar\.gz|zip)$'
version_prefix = "v"

[[tools.actionlint]]
version = "{actionlint_ver}"
backend = "aqua:rhysd/actionlint"

[tools.actionlint."platforms.linux-x64"]
checksum = "{}"
url = "https://example.invalid/actionlint.tar.gz"
repository_ids = {{ repository = "1", owner = "2" }}

[[tools.rust]]
version = "{rust_ver}"
backend = "core:rust"

[[tools.rust]]
version = "{rust_ver}"
backend = "core:rust"

[tools.rust.options]
components = "rustfmt,clippy"
"#,
        checksum(&"e".repeat(64)),
    );
    let lock = parse_mise_lockfile(&text)?;
    assert_eq!(lock.entries.get("rust").map(Vec::len), Some(2));
    let subjects = [
        subject(PinnedTool::Actionlint, &catalog)?,
        subject(PinnedTool::Rust, &catalog)?,
    ];
    let verdicts = audit_install_coverage(&lock, &subjects, "linux-x64");
    assert_eq!(verdicts[0], InstallCoverage::Verified);
    assert_eq!(verdicts[1], InstallCoverage::NoChecksums);
    Ok(())
}
