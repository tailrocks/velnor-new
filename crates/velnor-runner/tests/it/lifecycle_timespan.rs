#[test]
fn timespan_ticks_agree_with_every_form_measured_on_dotnet() {
    let wrong: Vec<_> = MEASURED_ON_DOTNET_8
        .iter()
        .filter(|(form, expected)| ticks(form) != *expected)
        .map(|(form, expected)| format!("{form:?}: expected {expected:?}, got {:?}", ticks(form)))
        .collect();

    assert!(wrong.is_empty(), "{wrong:#?}");
}
