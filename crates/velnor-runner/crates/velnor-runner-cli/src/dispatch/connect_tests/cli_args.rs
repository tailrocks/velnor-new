use clap::Parser;

#[test]
fn connect_requires_all_host_resource_limits() {
    let complete = [
        "velnor-host",
        "connect",
        "--connection-id",
        "example-repo",
        "--repo",
        "example/repo",
        "--repository-id",
        "123",
        "--scale-set",
        "ubuntu-26.04-scale-set",
        "--scale-set-label",
        "velnor",
        "--scale-set-label",
        "ubuntu-26.04-scale-set",
        "--source-policy-mode",
        "branch-restricted",
        "--event",
        "push",
        "--branch",
        "main",
        "--platform",
        "linux/amd64",
        "--runner-cpu-millicores",
        "1000",
        "--runner-memory-bytes",
        "2147483648",
        "--dind-cpu-millicores",
        "3000",
        "--dind-memory-bytes",
        "6442450944",
        "--operational-memory-reserve-bytes",
        "1073741824",
    ];
    assert!(crate::Cli::try_parse_from(complete).is_ok());
    let missing_memory = [
        "velnor-host",
        "connect",
        "--connection-id",
        "example-repo",
        "--repo",
        "example/repo",
        "--repository-id",
        "123",
        "--scale-set",
        "ubuntu-26.04-scale-set",
        "--scale-set-label",
        "velnor",
        "--scale-set-label",
        "ubuntu-26.04-scale-set",
        "--source-policy-mode",
        "branch-restricted",
        "--event",
        "push",
        "--branch",
        "main",
        "--platform",
        "linux/amd64",
        "--runner-cpu-millicores",
        "1000",
        "--runner-memory-bytes",
        "2147483648",
        "--dind-cpu-millicores",
        "3000",
        "--operational-memory-reserve-bytes",
        "1073741824",
    ];
    assert!(crate::Cli::try_parse_from(missing_memory).is_err());
}
