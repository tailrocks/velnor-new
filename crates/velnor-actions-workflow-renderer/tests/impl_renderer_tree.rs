#[test]
fn consumer_tree_has_exactly_three_sorted_paths() -> Result<(), RenderError> {
    let workflow = render_workflow_ir(
        &fixture_ir()?,
        WorkflowPolicy::ConsumerV1,
        None,
        &fixture_ctx(),
    )?;
    let tree = render_tree(&workflow, &actionlint_bytes()?, VERSION)?;
    assert_eq!(tree.files.len(), 3);
    assert!(tree.symlinks.is_empty());
    assert_eq!(tree.files[0].path, AGENTS_MD_PATH);
    assert_eq!(tree.files[1].path, ACTIONLINT_PATH);
    assert_eq!(tree.files[2].path, WORKFLOW_PATH);
    assert_eq!(tree.get(WORKFLOW_PATH), Some(workflow.as_str()));
    assert!(tree.get(".github/other.yml").is_none());
    assert!(tree.get(".github/CLAUDE.md").is_none());
    Ok(())
}

#[test]
fn consumer_tree_has_no_codeowners_merges_verify_and_rejects_candidate() -> Result<(), RenderError>
{
    let ir = fixture_ir()?;
    let ctx = fixture_ctx();
    // Config-selected verification jobs merge on the consumer policy.
    let with_verify = VelnorSupportWorkflow {
        validators: vec![ValidatorKind::Alint],
        candidate_validation: false,
    };
    let text = render_workflow_ir(&ir, WorkflowPolicy::ConsumerV1, Some(&with_verify), &ctx)?;
    assert!(text.contains("alint:"));
    // Velnor-only validators still fail closed on the consumer policy.
    let with_denied = VelnorSupportWorkflow {
        validators: vec![ValidatorKind::CargoDeny],
        candidate_validation: false,
    };
    assert!(render_workflow_ir(&ir, WorkflowPolicy::ConsumerV1, Some(&with_denied), &ctx).is_err());
    let with_candidate = VelnorSupportWorkflow {
        validators: Vec::new(),
        candidate_validation: true,
    };
    assert!(
        render_workflow_ir(&ir, WorkflowPolicy::ConsumerV1, Some(&with_candidate), &ctx).is_err()
    );
    let empty = VelnorSupportWorkflow {
        validators: Vec::new(),
        candidate_validation: false,
    };
    let text = render_workflow_ir(&ir, WorkflowPolicy::ConsumerV1, Some(&empty), &ctx)?;
    assert!(!text.contains("CODEOWNERS"));
    let tree = render_tree(&text, &actionlint_bytes()?, VERSION)?;
    assert_eq!(tree.files.len(), 3);
    assert!(tree.symlinks.is_empty());
    Ok(())
}

#[test]
fn consumer_rejects_support_job_ids_in_ir() -> Result<(), RenderError> {
    let mut ir = fixture_ir()?;
    let ctx = fixture_ctx();
    for forbidden in [
        "alint",
        "cargo-deny",
        "cargo-machete",
        "zizmor",
        "candidate",
    ] {
        let mut with_job = ir.clone();
        with_job.jobs.insert(forbidden.to_owned(), plan_job()?);
        assert!(
            render_workflow_ir(&with_job, WorkflowPolicy::ConsumerV1, None, &ctx).is_err(),
            "consumer accepted {forbidden}"
        );
    }
    assert!(render_workflow_ir(&ir, WorkflowPolicy::ConsumerV1, None, &ctx).is_ok());
    ir.jobs.remove("plan");
    assert!(render_workflow_ir(&ir, WorkflowPolicy::ConsumerV1, None, &ctx).is_err());
    Ok(())
}

