def inventory(root):
    result = []
    for current, directories, files in os.walk(root):
        if Path(current) == root and '.git' in directories:
            directories.remove('.git')
        for name in files:
            path = Path(current) / name
            if path.is_symlink():
                target = os.readlink(path)
                data = target.encode('utf-8')
                kind = {'type': 'symlink', 'target': target}
            else:
                data = path.read_bytes()
                kind = {'type': 'regular', 'executable': bool(path.stat().st_mode & 0o111)}
            result.append({'path': str(path.relative_to(root)), 'sha256': hashlib.sha256(data).hexdigest(),
                           'kind': kind})
    return sorted(result, key=lambda item: item['path'])


def seal(value):
    descriptor = os.memfd_create('fixture-context', os.MFD_CLOEXEC | os.MFD_ALLOW_SEALING)
    os.write(descriptor, json.dumps(value, separators=(',', ':')).encode())
    fcntl.fcntl(descriptor, fcntl.F_ADD_SEALS,
                fcntl.F_SEAL_WRITE | fcntl.F_SEAL_GROW | fcntl.F_SEAL_SHRINK | fcntl.F_SEAL_SEAL)
    return descriptor


def baseline(root, body):
    archive = io.BytesIO()
    manifest = b'[package]\nname="semver_probe"\nversion="0.1.0"\nedition="2021"\n'
    lock = (b'# This file is automatically @generated by Cargo.\n'
            b'# It is not intended for manual editing.\nversion = 4\n\n'
            b'[[package]]\nname = "semver_probe"\nversion = "0.1.0"\n')
    with tarfile.open(fileobj=archive, mode='w:gz') as tar:
        for name, data in [('Cargo.toml', manifest), ('Cargo.lock', lock), ('src/lib.rs', body)]:
            info = tarfile.TarInfo('semver_probe-0.1.0/' + name)
            info.size = len(data)
            info.mode = 0o644
            tar.addfile(info, io.BytesIO(data))
    checksum = hashlib.sha256(archive.getvalue()).hexdigest()
    projection = root / 'baselines' / checksum
    (projection / 'src').mkdir(parents=True)
    (projection / 'Cargo.toml').write_bytes(manifest)
    (projection / 'Cargo.lock').write_bytes(lock)
    (projection / 'src/lib.rs').write_bytes(body)
    for current, _, files in os.walk(projection):
        Path(current).chmod(0o555)
        for name in files:
            (Path(current) / name).chmod(0o444)
    return checksum, projection, inventory(projection)


def read_bytes(sock, count):
    result = bytearray()
    while len(result) < count:
        part = sock.recv(count - len(result))
        if not part:
            raise EOFError('source channel closed')
        result.extend(part)
    return bytes(result)


def call(sock, sequence, operation, context=None, index=None):
    request = {'seq': sequence, 'op': operation}
    if index is not None:
        request['index'] = index
    data = json.dumps(request, separators=(',', ':')).encode()
    sock.sendall(struct.pack('>I', len(data)) + data)
    if context is not None:
        descriptor = seal(context)
        try:
            sock.sendmsg([b'C'], [(socket.SOL_SOCKET, socket.SCM_RIGHTS, array.array('i', [descriptor]))])
        finally:
            os.close(descriptor)
    received, size = struct.unpack('>QI', read_bytes(sock, 12))
    if received != sequence:
        raise AssertionError('source channel returned wrong request')
    return read_bytes(sock, size)


def exercise(manager, root, initial, bound, semver, succeeds, seconds=300, expected_error=None, before_semver=None, index=0):
    deadline = time.clock_gettime_ns(time.CLOCK_BOOTTIME) + seconds * 1_000_000_000
    client, server = socket.socketpair()
    errors = []

    def serve():
        try:
            channel.serve(server, manager, lifecycle, executor, str(root), deadline, (root.stat().st_dev, root.stat().st_ino))
        except Exception as error:
            errors.append(error)
        finally:
            server.close()

    worker = threading.Thread(target=serve)
    worker.start()
    client.settimeout(max(seconds - 30, 10))
    try:
        assert call(client, 1, 'init', initial) == b''
        assert json.loads(call(client, 2, 'metadata'))['workspace_root'] == str(root / 'source')
        assert call(client, 3, 'bind', bound) == b''
        if before_semver is not None:
            before_semver()
        try:
            result = call(client, 4, 'semver', semver, index)
        except (EOFError, ConnectionError) as error:
            if succeeds:
                raise AssertionError(f'valid semver closed channel: {errors}') from error
        else:
            if not succeeds:
                raise AssertionError('semver failure was accepted')
            assert result == b''
            assert call(client, 5, 'close') == b''
    finally:
        client.close()
        worker.join(timeout=30)
    if worker.is_alive():
        raise AssertionError('supervisor failed to quiesce')
    if succeeds and errors:
        raise AssertionError(f'supervisor rejected valid semver: {errors}')
    if not succeeds and (len(errors) != 1 or str(errors[0]) != expected_error):
        raise AssertionError(f'unexpected semver failure: {errors}')


