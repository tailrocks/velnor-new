//! Generated `.github/dco.yml` rendering for the cncf/dco2 GitHub App.

use velnor_actions_contract::{DCO_CONFIG_PATH, DcoConfig};

use crate::RenderError;
use crate::marker::with_marker;
use crate::render::RenderedFile;

/// Render `.github/dco.yml` with the versioned marker.
///
/// Keys appear in dco2's reference order (`allowOverrideAction`,
/// `allowRemediationCommits`, `require`); unset keys are omitted so dco2's
/// documented defaults apply. Values are booleans only, so no escaping exists.
///
/// # Errors
///
/// Returns [`RenderError`] if the version is invalid.
pub fn render_dco_yml(config: &DcoConfig, version: &str) -> Result<RenderedFile, RenderError> {
    let mut lines: Vec<String> = Vec::new();
    if let Some(allow) = config.allow_override_action {
        lines.push(format!("allowOverrideAction: {allow}"));
    }
    if let Some(remediation) = &config.allow_remediation_commits {
        lines.push("allowRemediationCommits:".to_owned());
        if let Some(individual) = remediation.individual {
            lines.push(format!("  individual: {individual}"));
        }
        if let Some(third_party) = remediation.third_party {
            lines.push(format!("  thirdParty: {third_party}"));
        }
    }
    if let Some(require) = &config.require {
        lines.push("require:".to_owned());
        lines.push(format!("  members: {}", require.members));
    }
    let body = lines.join("\n") + "\n";
    Ok(RenderedFile {
        path: DCO_CONFIG_PATH.to_owned(),
        bytes: with_marker(version, &body)?,
    })
}

#[cfg(test)]
mod tests {
    use super::render_dco_yml;
    use velnor_actions_contract::{DcoConfig, DcoRemediationCommits, DcoRequire};

    const MARKER: &str =
        "# Generated by Velnor Actions 0.1.22; edit .velnor/config.toml and regenerate.\n";

    fn render(config: &DcoConfig) -> String {
        render_dco_yml(config, "0.1.22").expect("render").bytes
    }

    #[test]
    fn remediation_commits_golden() {
        let config = DcoConfig {
            allow_remediation_commits: Some(DcoRemediationCommits {
                individual: Some(true),
                third_party: Some(true),
            }),
            ..DcoConfig::default()
        };
        assert_eq!(
            render(&config),
            format!("{MARKER}allowRemediationCommits:\n  individual: true\n  thirdParty: true\n")
        );
    }

    #[test]
    fn members_golden_matches_the_former_hand_written_file() {
        let config = DcoConfig {
            require: Some(DcoRequire { members: false }),
            ..DcoConfig::default()
        };
        assert_eq!(
            render(&config),
            format!("{MARKER}require:\n  members: false\n")
        );
    }

    #[test]
    fn every_key_renders_in_reference_order() {
        let config = DcoConfig {
            allow_override_action: Some(false),
            allow_remediation_commits: Some(DcoRemediationCommits {
                individual: Some(true),
                third_party: None,
            }),
            require: Some(DcoRequire { members: true }),
        };
        assert_eq!(
            render(&config),
            format!(
                "{MARKER}allowOverrideAction: false\nallowRemediationCommits:\n  individual: true\nrequire:\n  members: true\n"
            )
        );
    }
}
