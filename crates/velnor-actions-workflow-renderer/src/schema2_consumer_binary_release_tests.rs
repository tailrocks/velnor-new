#[test]
fn renders_four_isolated_jobs_bound_to_exact_package_and_source() {
    let rendered = render_consumer_binary_release(&spec()).expect("workflow renders");
    let yaml = rendered.bytes;
    assert_eq!(rendered.path, ".github/workflows/binary-release.yml");
    assert!(yaml.starts_with("# Generated by Velnor Actions 0.1.4;"));
    assert!(yaml.contains("workflow_dispatch: {}"));
    assert!(!yaml.contains("inputs:"));
    assert!(yaml.contains("consumer-binary-release-${{ github.repository }}"));
    assert!(yaml.contains("ref:"));
    assert!(yaml.contains("needs.release-eligibility.outputs.source_sha"));
    assert!(yaml.contains("cargo metadata --format-version 1 --locked --no-deps"));
    assert!(yaml.contains("--package repo-scan --bin repo-scan --target aarch64-apple-darwin"));
    assert!(yaml.contains("PACKAGE_NAME-v$version"));
    assert!(
        yaml.contains("actions/attest-build-provenance@4d101475d8b20a2381f78447822ac1eab6504dd8")
    );
    assert!(yaml.contains("contents: write"));
    assert!(yaml.contains("attestations: write"));
    assert!(!yaml.contains("actions: write"));
    let build_start = yaml.find("  build-binary:").expect("build job");
    let attest_start = yaml.find("  attest-binary:").expect("attest job");
    let publish_start = yaml.find("  publish-binary:").expect("publish job");
    let eligibility_start = yaml
        .find("  release-eligibility:")
        .expect("eligibility job");
    let eligibility_job = &yaml[eligibility_start..build_start];
    let build_job = &yaml[build_start..attest_start];
    let attest_job = &yaml[attest_start..publish_start];
    let publish_job = &yaml[publish_start..];
    assert!(eligibility_job.contains("timeout-minutes: 75"));
    assert!(!build_job.contains("actions: write"));
    assert!(build_job.contains("contents: read"));
    assert!(!build_job.contains("contents: write"));
    assert!(!build_job.contains("id-token: write"));
    assert!(attest_job.contains("id-token: write"));
    assert!(attest_job.contains("attestations: write"));
    assert!(!attest_job.contains("contents: write"));
    assert!(publish_job.contains("contents: write"));
    assert!(publish_job.contains("timeout-minutes: 75"));
    assert!(publish_job.contains("actions: read"));
    assert!(publish_job.contains("attestations: read"));
    assert!(!publish_job.contains("id-token: write"));
    assert!(publish_job.contains("environment:"));
    assert!(publish_job.contains("name: consumer-binary-release"));
    assert!(publish_job.contains("IMMUTABILITY_READ_TOKEN"));
    assert!(yaml.contains("default_branch='stable'"));
    assert!(yaml.contains("refs/heads/$default_branch"));
    assert!(yaml.contains("repository='example/repo-scan'"));
    assert!(yaml.contains("binary-release.yml@refs/heads/$default_branch"));
    assert!(!yaml.contains("tailrocks/velnor-new"));
    assert!(!yaml.contains("--clobber"));
    assert!(yaml.contains("require_absent"));
    assert!(yaml.contains("assert_protected_environment"));
    assert!(yaml.contains("IMMUTABILITY_READ_TOKEN"));
    assert!(yaml.contains("consumer-binary-release"));
    assert!(yaml.contains("2026.10.5"));
    assert!(yaml.contains("aarch64-apple-darwin"));
    assert!(yaml.contains("CARGO_TARGET_DIR"));
    assert!(yaml.contains("required-features"));
    assert!(yaml.contains("isImmutable == true"));
    assert!(yaml.contains("gh release create"));
    assert!(yaml.contains("--verify-tag --draft --latest=false"));
}

#[test]
fn rejects_unsafe_consumer_identity_and_shell_values() {
    let mut unsafe_repo = spec();
    unsafe_repo.repository = "example/repo-scan;touch".to_owned();
    assert!(render_consumer_binary_release(&unsafe_repo).is_err());

    let mut unsafe_branch = spec();
    unsafe_branch.default_branch = "stable;touch /tmp/pwned".to_owned();
    assert!(render_consumer_binary_release(&unsafe_branch).is_err());

    let mut unsafe_target = spec();
    unsafe_target.bin = "repo-scan;touch".to_owned();
    assert!(render_consumer_binary_release(&unsafe_target).is_err());
}
