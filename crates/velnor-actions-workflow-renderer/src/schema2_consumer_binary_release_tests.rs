fn install_argv(tools: &[&str]) -> Vec<String> {
    let mut command = vec![
        "mise".to_owned(),
        "--no-config".to_owned(),
        "--no-env".to_owned(),
        "--no-hooks".to_owned(),
        "install".to_owned(),
    ];
    command.extend(tools.iter().map(|tool| (*tool).to_owned()));
    command
}

fn exec_argv(tool: &str, program: &str, args: &[&str]) -> Vec<String> {
    let mut command = vec![
        "mise".to_owned(),
        "--no-config".to_owned(),
        "--no-env".to_owned(),
        "--no-hooks".to_owned(),
        "exec".to_owned(),
        tool.to_owned(),
        "--".to_owned(),
        program.to_owned(),
    ];
    command.extend(args.iter().map(|arg| (*arg).to_owned()));
    command
}

