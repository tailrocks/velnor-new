/// Text of one top-level job block.
fn job_text<'a>(yaml: &'a str, id: &str) -> &'a str {
    let start = yaml
        .find(&format!("\n  {id}:\n"))
        .unwrap_or_else(|| panic!("job {id}:\n{yaml}"));
    let rest = &yaml[start + 1..];
    let end = rest[2..]
        .find("\n  ")
        .and_then(|_| {
            rest.match_indices('\n').map(|(at, _)| at).find(|at| {
                let line = &rest[at + 1..];
                line.starts_with("  ") && !line.starts_with("   ") && *at > 0
            })
        })
        .unwrap_or(rest.len());
    &rest[..end]
}

fn named_step_text<'a>(job: &'a str, name: &str) -> &'a str {
    let marker = format!("      - name: {name}\n");
    let start = job
        .find(&marker)
        .unwrap_or_else(|| panic!("missing step {name:?}:\n{job}"));
    let rest = &job[start..];
    let step_indent = rest.lines().next().expect("step line").len()
        - rest.lines().next().expect("step line").trim_start().len();
    let end = rest
        .match_indices('\n')
        .map(|(at, _)| at + 1)
        .find(|at| {
            let line = &rest[*at..];
            let indent = line.len() - line.trim_start().len();
            indent == step_indent && line.trim_start().starts_with("- name: ")
        })
        .unwrap_or(rest.len());
    &rest[..end]
}

fn assert_jactionlint_verifier_boundary(job: &str) {
    let step = named_step_text(job, "Verify jactionlint");
    assert_eq!(crate::VERIFY_PATH, "/usr/bin:/bin:/usr/sbin:/sbin");
    assert!(
        step.contains("shell: /bin/bash --noprofile --norc -p -e -o pipefail {0}"),
        "{step}"
    );
    let run = step
        .lines()
        .find_map(|line| line.trim_start().strip_prefix("run: "))
        .expect("verifier run command");
    let run = run.strip_prefix('"').unwrap_or(run);
    assert!(run.starts_with(VERIFY_RUN_PREFIX), "{step}");
    let env = step.split_once("        env:\n").expect("verifier env").1;
    let mut entries = std::collections::BTreeMap::new();
    for line in env
        .lines()
        .take_while(|line| line.starts_with("          "))
    {
        let (key, value) = line.trim().split_once(": ").expect("env entry");
        assert!(entries.insert(key, value).is_none(), "duplicate {key}");
    }
    let expected = crate::toolchain_env::STEP_CREDENTIAL_DENYLIST
        .into_iter()
        .chain(crate::toolchain_env::STEP_ENDPOINT_DENYLIST)
        .chain(std::iter::once("PATH"))
        .collect::<std::collections::BTreeSet<_>>();
    assert_eq!(
        entries
            .keys()
            .copied()
            .collect::<std::collections::BTreeSet<_>>(),
        expected
    );
    for key in crate::toolchain_env::STEP_CREDENTIAL_DENYLIST
        .into_iter()
        .chain(crate::toolchain_env::STEP_ENDPOINT_DENYLIST)
    {
        assert_eq!(entries.get(key), Some(&"\"\""), "{key}");
    }
    assert_eq!(entries.get("PATH"), Some(&"/usr/bin:/bin:/usr/sbin:/sbin"));
}

#[test]
fn renders_daily_schedule_only_workflow_with_four_jobs() {
    let file = render_upgrades_workflow(&spec()).expect("render");
    assert_eq!(file.path, ".github/workflows/upgrades.yml");
    let yaml = &file.bytes;
    assert!(
        yaml.starts_with("# Generated by Velnor Actions 0.1.0"),
        "{yaml}"
    );
    assert!(yaml.contains("cron: 17 5 * * *"), "daily:\n{yaml}");
    assert!(yaml.contains("workflow_dispatch:"), "{yaml}");
    let on_start = yaml.find("\"on\":").expect("on");
    let on_end = yaml.find("\npermissions:").expect("permissions");
    assert_eq!(
        &yaml[on_start..on_end],
        "\"on\":\n  schedule:\n    - cron: 17 5 * * *\n  workflow_dispatch: {}",
        "schedule and manual runs only, never a pull-request check"
    );
    for id in ["prepare", "verify", "publish", "freshness"] {
        assert!(yaml.contains(&format!("\n  {id}:\n")), "{id}:\n{yaml}");
    }
    assert!(yaml.contains("cancel-in-progress: false"), "{yaml}");
}

#[test]
fn prepare_holds_no_credential_and_runs_without_cooldown() {
    let yaml = render_upgrades_workflow(&spec()).expect("render").bytes;
    let prepare = job_text(&yaml, "prepare");
    assert!(
        prepare.contains("MISE_MINIMUM_RELEASE_AGE: 0s"),
        "{prepare}"
    );
    assert!(!prepare.contains("secrets."), "{prepare}");
    assert!(!prepare.contains(": write"), "{prepare}");
    // The only credential is the read-only `github.token` of the release
    // step, which runs before any repository code and ends before the bump.
    assert_eq!(
        prepare.matches("GH_TOKEN: ${{ github.token }}").count(),
        1,
        "{prepare}"
    );
    assert!(!prepare.contains("steps.upgrade-token"), "{prepare}");
    let release = prepare
        .find("GH_TOKEN: ${{ github.token }}")
        .expect("release step token");
    let bump = prepare.find("name: Bump every pin").expect("bump step");
    assert!(
        prepare.find("name: Resolve and verify the latest Velnor release") < Some(release)
            && release < bump,
        "{prepare}"
    );
    assert!(
        prepare.contains("persist-credentials: \"false\""),
        "{prepare}"
    );
    assert!(
        prepare.contains(
            "github.ref == format('refs/heads/{0}', github.event.repository.default_branch)"
        ),
        "default branch only:\n{prepare}"
    );
    for scope in [
        "upgrade_velnor_pinned_ahead",
        "mise upgrade --bump",
        "mise lock --platform linux-x64,linux-arm64,macos-arm64",
        "cargo upgrade --incompatible --pinned",
        "cargo update --manifest-path",
        "bun update --latest --ignore-scripts",
        "bump-gradle-catalog.py",
        "velnor/bin/velnor-actions\\\" generate",
        "VELNOR_GENERATE_TOOLS: jactionlint@2.3.0 shellcheck@0.11.0",
        "rust_channel_manifest_not_catalogued",
        "git diff --cached --no-renames",
    ] {
        assert!(prepare.contains(scope), "{scope}:\n{prepare}");
    }
    assert!(prepare.contains(&format!("VELNOR_CARGO_EDIT_VERSION: {CARGO_EDIT_VERSION}")));
}

#[test]
fn publish_mints_a_repository_scoped_write_token_and_never_force_pushes() {
    let yaml = render_upgrades_workflow(&spec()).expect("render").bytes;
    let publish = job_text(&yaml, "publish");
    assert!(publish.contains("needs: verify"), "{publish}");
    assert!(
        publish.contains("client-id: ${{ vars.VELNOR_DEPS_APP_ID }}"),
        "{publish}"
    );
    assert!(
        publish.contains("private-key: ${{ secrets.VELNOR_DEPS_APP_PRIVATE_KEY }}"),
        "{publish}"
    );
    assert!(
        publish.contains("repositories: ${{ github.event.repository.name }}"),
        "{publish}"
    );
    assert!(publish.contains("permission-contents: write"), "{publish}");
    assert!(
        publish.contains("permission-pull-requests: write"),
        "{publish}"
    );
    assert!(
        publish.contains("permission-workflows: ${{ needs.verify.outputs.workflows }}"),
        "workflows only when the verified tree changes one:\n{publish}"
    );
    assert_eq!(publish.matches("permission-").count(), 3, "{publish}");
    assert!(publish.contains("skip-token-revoke: false"), "{publish}");
    assert!(
        !publish.contains("--force"),
        "fast-forward only:\n{publish}"
    );
    assert!(publish.contains("git commit-tree"), "{publish}");
    assert!(publish.contains("upgrade_patch_path_rejected"), "{publish}");
    // Every check runs in a step before the token exists, with no token.
    let check = publish
        .find("name: Check the patch is the verified upgrade")
        .expect("check step");
    let mint = publish
        .find("name: Mint a short-lived token")
        .expect("mint step");
    let push = publish.find("name: Push the upgrade branch").expect("push");
    assert!(check < mint && mint < push, "{publish}");
    assert!(!publish[check..mint].contains("TOKEN"), "{publish}");
    assert!(publish[check..mint].contains("upgrade_patch_unverified"));
    assert!(publish[check..mint].contains("velnor_upgrade_check_patch_applies"));
    assert!(!publish[push..].contains("git apply"), "{publish}");
    assert!(publish.contains("mise --no-config --no-env --no-hooks install gh@2.103.0"));
    assert!(
        publish.contains("permissions:\n      contents: read"),
        "{publish}"
    );
}

