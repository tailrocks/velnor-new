use std::os::unix::fs::PermissionsExt;
use std::process::Command;

use velnor_actions_contract::workflow::cache_family::CacheFamily;

use super::{
    CACHE_PRUNE_FALLBACK_RUNNER, CACHE_PRUNE_PATH, prune_script, prune_targets,
    render_cache_prune_yml,
};

fn render(label: &str) -> String {
    render_cache_prune_yml(label, "main", "0.1.22")
        .expect("render")
        .bytes
}

#[test]
fn the_workflow_is_marked_push_only_and_gated_on_the_protected_ref() {
    let file = render_cache_prune_yml("ubuntu-26.04", "main", "0.1.22").expect("render");
    assert_eq!(file.path, CACHE_PRUNE_PATH);
    assert!(file.bytes.starts_with(
        "# Generated by Velnor Actions 0.1.22; edit .velnor/config.toml and regenerate.\n"
    ));
    let yaml = &file.bytes;
    assert!(yaml.contains("\"on\":\n  push:\n    branches:\n      - main\n"));
    assert!(!yaml.contains("pull_request"), "never on a pull request");
    assert!(yaml.contains("if: github.ref_protected == true\n"));
    assert!(
        yaml.contains("permissions: {}\n"),
        "workflow scope is empty"
    );
    assert_eq!(yaml.matches("actions: write").count(), 1);
    assert!(!yaml.contains("actions/checkout"), "no code is checked out");
    assert!(yaml.contains("runs-on: ubuntu-26.04\n"));
}

#[test]
fn a_branch_or_label_outside_the_grammar_is_rejected_or_falls_back() {
    assert!(render_cache_prune_yml("ubuntu-26.04", "ma in", "0.1.22").is_err());
    assert!(render_cache_prune_yml("ubuntu-26.04", "", "0.1.22").is_err());
    let scale = render("velnor");
    assert!(
        scale.contains("runs-on: velnor\n")
            || scale.contains(&format!("runs-on: {CACHE_PRUNE_FALLBACK_RUNNER}\n"))
    );
}

#[test]
fn every_family_is_pruned_by_its_own_trusted_prefix_and_retention() {
    let targets = prune_targets();
    assert_eq!(targets.len(), CacheFamily::ALL.len());
    let script = prune_script();
    for family in CacheFamily::ALL {
        let prefix = format!("{}trusted-", family.key_prefix());
        assert!(
            script.contains(&format!(
                "prune '{prefix}' {}",
                family.spec().retained_entries
            )),
            "{prefix}"
        );
    }
    assert!(script.contains("--ref \"$ref\""), "one ref only");
    assert!(script.contains("ref=\"$GITHUB_REF\""));
    assert!(!script.contains("delete --all"), "no global prune");
    assert!(!script.contains("-pr-"), "the pr scope is never listed");
}

/// Run the generated script against a stub `gh` that serves a fixed list.
#[test]
fn the_script_keeps_the_newest_entries_per_unit_and_deletes_the_rest() {
    let root = std::env::temp_dir().join(format!("velnor-prune-{}", std::process::id()));
    drop(std::fs::remove_dir_all(&root));
    std::fs::create_dir_all(root.join("bin")).expect("bin");
    std::fs::create_dir_all(root.join("runner")).expect("runner");
    let digest = |n: u8| format!("s256-{}", format!("{n:02x}").repeat(32));
    let unit = |u: u8| {
        format!(
            "velnor-v1-mbx-bundle-trusted-s256-{}",
            format!("{u:02x}").repeat(32)
        )
    };
    // Newest first, as `--sort created_at --order desc` returns them.
    let list = format!(
        "11\t{a}-{d1}\n12\t{a}-{d2}\n13\t{b}-{d1}\n14\t{a}-{d3}\n",
        a = unit(0xaa),
        b = unit(0xbb),
        d1 = digest(1),
        d2 = digest(2),
        d3 = digest(3)
    );
    std::fs::write(root.join("list.tsv"), list).expect("list");
    let stub = "#!/bin/sh\ncase \"$1 $2\" in\n  'cache list') case \"$4\" in velnor-v1-mbx-bundle-trusted-*) cat \"$STUB_LIST\" ;; esac ;;\n  'cache delete') printf '%s\\n' \"$3\" >> \"$STUB_DELETED\" ;;\nesac\n";
    let gh = root.join("bin/gh");
    std::fs::write(&gh, stub).expect("stub");
    std::fs::set_permissions(&gh, std::fs::Permissions::from_mode(0o755)).expect("chmod");
    let output = Command::new("sh")
        .args(["-c", &prune_script()])
        .env(
            "PATH",
            format!(
                "{}:{}",
                root.join("bin").display(),
                std::env::var("PATH").unwrap_or_default()
            ),
        )
        .env("RUNNER_TEMP", root.join("runner"))
        .env("GITHUB_REF", "refs/heads/main")
        .env("STUB_LIST", root.join("list.tsv"))
        .env("STUB_DELETED", root.join("deleted"))
        .output()
        .expect("script runs");
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    let deleted = std::fs::read_to_string(root.join("deleted")).expect("deleted");
    // Unit aa keeps its newest entry (retained 1): 11 stays, 12 and 14 go;
    // unit bb has a single entry and is untouched.
    assert_eq!(deleted.lines().collect::<Vec<_>>(), ["12", "14"]);
    drop(std::fs::remove_dir_all(&root));
}
