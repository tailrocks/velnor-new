//! Generator-owned composites for fixed tool-integrity verifier steps.
//!
//! The orchestrator supplies the canonical typed shell step. This module
//! renders it with the same credential scrub/unset validation as an ordinary
//! step and the fixed trusted interpreter used while cached bytes are on PATH.

use velnor_actions_contract::workflow::{RUST_VERIFIER_USES, Step, StepKind, StepRole};

use crate::tree::RenderedFile;
use crate::{RenderError, marker, steps, yaml::render_yaml};

/// Fixed local action reference for Velnor's executable digest check.
pub const VERIFY_JACTIONLINT_USES: &str = "./.github/actions/velnor-verify-jactionlint";

/// Render one of the three canonical verification composites.
///
/// The input step must be the canonical credential-scrubbed shell template
/// for the selected action. The orchestrator audits its expected bytes and
/// every call independently; this renderer only accepts the three fixed
/// action identities and their fixed step-role/name shape.
///
/// # Errors
///
/// Returns [`RenderError`] when the action identity, shell step shape,
/// generated bytes, or output path is invalid.
pub fn render_verifier_composite(
    uses: &str,
    step: &Step,
    version: &str,
) -> Result<RenderedFile, RenderError> {
    let (action_name, step_name, expected_role) = if uses == RUST_VERIFIER_USES[0] {
        (
            "Velnor restored Rust verifier",
            "Verify restored Rust toolchain",
            Some(StepRole::VerifyRustManifest),
        )
    } else if uses == RUST_VERIFIER_USES[1] {
        (
            "Velnor Rust channel verifier",
            crate::VERIFY_RUST_TOOLCHAIN_STEP,
            Some(StepRole::VerifyRustManifest),
        )
    } else if uses == VERIFY_JACTIONLINT_USES {
        (
            "Velnor jactionlint executable verifier",
            "Verify jactionlint",
            None,
        )
    } else {
        return Err(RenderError::BadActionRef(format!(
            "unregistered_verifier:{uses}"
        )));
    };
    if step.name != step_name
        || step.role != expected_role
        || step.parallel
        || step.id.is_some()
        || step.condition.is_some()
        || !matches!(&step.kind, StepKind::Shell { .. })
    {
        return Err(RenderError::InvalidWorkflow(format!(
            "noncanonical_verifier_step:{uses}"
        )));
    }

    let shell = crate::document_steps::verifier_shell_step_to_yaml(step)?;
    let mut body = crate::composite::composite_yaml(action_name, vec![shell])?;
    crate::project_tool_resolver::bind_workflow(&mut body)?;
    let bytes = marker::with_marker(version, &render_yaml(&body))?;
    steps::scan_for_private_subcommands(&bytes)?;
    let logical = uses
        .strip_prefix("./.github/actions/")
        .ok_or_else(|| RenderError::BadActionRef(format!("nonlocal_verifier:{uses}")))?;
    let path = format!(".github/actions/{logical}/action.yml");
    crate::guard::validate_tree_path(&path)?;
    Ok(RenderedFile { path, bytes })
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use velnor_actions_contract::workflow::{RUST_VERIFIER_USES, Step, StepRole};

    use super::{VERIFY_JACTIONLINT_USES, render_verifier_composite};
    use crate::VERIFY_SHELL;

    fn rust_step(uses: &str) -> Step {
        let restored = uses == RUST_VERIFIER_USES[0];
        let name = if restored {
            "Verify restored Rust toolchain"
        } else {
            crate::VERIFY_RUST_TOOLCHAIN_STEP
        };
        let mut step = crate::steps::shell_step(
            name,
            vec![
                "sh".to_owned(),
                "-c".to_owned(),
                "set -eu; echo verified; echo rust@${VELNOR_TOOL_RUST}".to_owned(),
            ],
            BTreeMap::from([
                (
                    "RUSTUP_HOME".to_owned(),
                    "${{ runner.temp }}/velnor/rustup".to_owned(),
                ),
                (
                    "CARGO_HOME".to_owned(),
                    "${{ runner.temp }}/velnor/cargo".to_owned(),
                ),
            ]),
        )
        .expect("canonical scrubbed shell");
        step.role = Some(StepRole::VerifyRustManifest);
        step
    }

    #[test]
    fn verifier_composite_keeps_scrubbed_shell_body_homes_and_trusted_shell() {
        let file = render_verifier_composite(
            RUST_VERIFIER_USES[0],
            &rust_step(RUST_VERIFIER_USES[0]),
            "0.1.40",
        )
        .expect("fixed composite");
        assert_eq!(
            file.path,
            ".github/actions/velnor-verify-restored-rust/action.yml"
        );
        assert!(file.bytes.contains(&format!("shell: {VERIFY_SHELL}")));
        assert!(file.bytes.contains("RUSTUP_HOME:"));
        assert!(file.bytes.contains("${{ runner.temp }}/velnor/rustup"));
        assert!(file.bytes.contains("CARGO_HOME:"));
        assert!(file.bytes.contains("${{ runner.temp }}/velnor/cargo"));
        let resolver = file
            .bytes
            .find("name: Resolve project tool versions")
            .unwrap_or_else(|| panic!("composite lacks its project resolver:\n{}", file.bytes));
        let verifier = file
            .bytes
            .find("name: Verify restored Rust toolchain")
            .expect("verifier step");
        assert!(resolver < verifier, "{0}", file.bytes);
        assert!(file.bytes.contains("velnor_tool VELNOR_TOOL_RUST '"));
        assert!(file.bytes.contains("GITHUB_TOKEN: \"\""));
        let prelude = format!(
            "unset {};",
            crate::toolchain_env::CREDENTIAL_UNSET_VARS.join(" ")
        );
        assert!(file.bytes.contains(&prelude));
        assert!(file.bytes.contains("set -eu; echo verified"));
    }

    #[test]
    fn jactionlint_composite_uses_the_trusted_shell_and_scrubbed_script() {
        let step = crate::steps::shell_step(
            "Verify jactionlint",
            vec![
                "sh".to_owned(),
                "-c".to_owned(),
                "set -eu; echo digest-verified; echo jactionlint@${VELNOR_TOOL_JACTIONLINT}"
                    .to_owned(),
            ],
            BTreeMap::new(),
        )
        .expect("canonical scrubbed shell");
        let file = render_verifier_composite(VERIFY_JACTIONLINT_USES, &step, "0.1.40")
            .expect("fixed jactionlint composite");
        assert_eq!(
            file.path,
            ".github/actions/velnor-verify-jactionlint/action.yml"
        );
        assert!(file.bytes.contains(&format!("shell: {VERIFY_SHELL}")));
        assert!(file.bytes.contains("GITHUB_TOKEN: \"\""));
        let prelude = format!(
            "unset {};",
            crate::toolchain_env::CREDENTIAL_UNSET_VARS.join(" ")
        );
        assert!(file.bytes.contains(&prelude));
        assert!(file.bytes.contains("digest-verified"));
        let resolver = file
            .bytes
            .find("name: Resolve project tool versions")
            .unwrap_or_else(|| panic!("composite lacks its project resolver:\n{}", file.bytes));
        let verifier = file
            .bytes
            .find("name: Verify jactionlint")
            .expect("verifier step");
        assert!(resolver < verifier, "{0}", file.bytes);
        assert!(file.bytes.contains("velnor_tool VELNOR_TOOL_JACTIONLINT '"));
    }

    #[test]
    fn verifier_composite_rejects_unregistered_paths_and_mutated_step_identity() {
        let canonical = rust_step(RUST_VERIFIER_USES[1]);
        for uses in [
            "./.github/actions/velnor-verify-rust-manifest/",
            "./.github/actions/velnor-verify-rust-manifest@deadbeef",
            "./.github/actions/../velnor-verify-rust-manifest",
            "./.github/actions/velnor-verify-rust-manifest-extra",
        ] {
            assert!(
                render_verifier_composite(uses, &canonical, "0.1.40").is_err(),
                "unexpected accepted path {uses}"
            );
        }
        assert!(render_verifier_composite(VERIFY_JACTIONLINT_USES, &canonical, "0.1.40").is_err());
        let mut changed_name = canonical.clone();
        changed_name.name = "anything".to_owned();
        assert!(render_verifier_composite(RUST_VERIFIER_USES[1], &changed_name, "0.1.40").is_err());
        let mut changed_role = canonical;
        changed_role.role = None;
        assert!(render_verifier_composite(RUST_VERIFIER_USES[1], &changed_role, "0.1.40").is_err());
    }
}
