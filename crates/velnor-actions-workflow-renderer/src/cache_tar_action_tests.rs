use super::action_file;

const STAGED: &str = "$RUNNER_TEMP/velnor/bin/velnor-actions-0.1.4";

#[test]
fn generated_composite_installs_aliases_and_returns_only_its_local_path()
-> Result<(), crate::RenderError> {
    let file = action_file(STAGED, "0.1.4", "0.1.5")?;
    let body = file.bytes;

    assert_eq!(
        file.path,
        ".github/actions/velnor-cache-tar-launchers/action.yml"
    );
    assert!(body.contains("Velnor cache tar adapters"));
    assert!(body.contains("helper-sha256"));
    assert!(body.contains("${{ inputs.helper-sha256 }}"));
    assert!(body.contains("VELNOR_INTERNAL_OP: install-cache-tar-aliases-v1"));
    assert!(body.contains("VELNOR_CACHE_TAR_VERSION: 0.1.4"));
    assert!(body.contains("${{ steps.install.outputs.path }}"));
    assert!(!body.contains("GITHUB_PATH"));
    Ok(())
}

#[test]
fn generated_composite_requires_the_staged_binary_version() {
    assert!(action_file(STAGED, "0.1.5", "0.1.5").is_err());
}

#[test]
fn generated_tree_includes_launcher_composite_only_for_cache_jobs() -> Result<(), crate::RenderError>
{
    use std::collections::BTreeMap;

    use velnor_actions_contract::{Job, StepRole, workflow::JobTimeout};

    let step = crate::steps::cache_tar_launcher_step(&"a".repeat(64))?;
    let job = Job {
        services: Vec::new(),
        display_name: "Cache job".to_owned(),
        runs_on: "ubuntu-26.04".to_owned(),
        check_runner: None,
        timeout_minutes: JobTimeout::REQUIRED,
        needs: Vec::new(),
        condition: None,
        permissions: None,
        cache_mode: None,
        environment: None,
        steps: vec![step],
    };
    assert_eq!(job.steps[0].role, Some(StepRole::CacheTarLaunchers));
    let jobs = BTreeMap::from([("cache".to_owned(), job)]);
    let files = crate::render_cache_files::with_runtime_identity_and_cache_tar_files(
        Vec::new(),
        &jobs,
        "0.1.5",
        "$RUNNER_TEMP/velnor/bin/velnor-actions-0.1.4",
        "0.1.4",
        &[],
    )?;

    assert_eq!(files.len(), 1);
    assert_eq!(
        files[0].path,
        ".github/actions/velnor-cache-tar-launchers/action.yml"
    );
    let body = files[0].bytes.as_str();
    assert!(body.starts_with("# Generated by Velnor Actions 0.1.5;"));

    let no_cache = crate::render_cache_files::with_runtime_identity_and_cache_tar_files(
        Vec::new(),
        &BTreeMap::new(),
        "0.1.5",
        "$RUNNER_TEMP/velnor/bin/velnor-actions-0.1.4",
        "0.1.4",
        &[],
    )?;
    assert_eq!(no_cache, Vec::new());
    Ok(())
}
