//! Fakes and helpers for the upgrade-script sandbox: the stub `mise` and
//! `gh` (which serves the fixture release store and checks fixture
//! attestations), the stand-in `velnor-actions`, and digest helpers.

use std::error::Error;
use std::path::Path;
use std::process::{Command, Output};

use crate::schema2::git_fixture;

type TestResult<T = ()> = Result<T, Box<dyn Error>>;

/// Fake `mise`: the pinned GitHub CLI call runs the fake `gh`; `ls` reports
/// the project Rust; anything else is logged and succeeds, unless a per-test
/// `mise-impl` takes over.
pub(super) const FAKE_MISE: &str = r#"#!/bin/sh
printf 'mise %s\n' "$*" >> "$SANDBOX_LOG"
if [ "$1 $2 $3 $4" = "--no-config --no-env --no-hooks exec" ]; then
  case "$5" in gh@*) shift 5; [ "$1" = -- ] && shift; exec "$@" ;; esac
fi
if [ -x "$SANDBOX_BIN/mise-impl" ]; then exec "$SANDBOX_BIN/mise-impl" "$@"; fi
case "$1" in ls) printf '%s\n' '{"rust":[{"requested_version":"1.98.1"}]}' ;; esac
exit 0
"#;

/// Fake `gh`: logs every call and serves the fixture release store.
pub(super) const FAKE_GH: &str = r#"#!/bin/sh
printf 'gh %s\n' "$*" >> "$SANDBOX_LOG"
if [ -x "$SANDBOX_BIN/gh-impl" ]; then exec "$SANDBOX_BIN/gh-impl" "$@"; fi
sha() { if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1"; else shasum -a 256 "$1"; fi | cut -d' ' -f1; }
case "$1" in
  api)
    expr=
    while [ $# -gt 0 ]; do [ "$1" = --jq ] && expr=$2; shift; done
    exec jq -r "$expr" "$SANDBOX_ROOT/releases.json" ;;
  release)
    [ "$2" = download ] || exit 2
    tag=$3; shift 3; dir=; patterns=
    while [ $# -gt 0 ]; do
      case "$1" in --dir) dir=$2; shift ;; --pattern) patterns="$patterns $2"; shift ;; esac
      shift
    done
    for pattern in $patterns; do cp "$SANDBOX_ROOT/releases/$tag/$pattern" "$dir/" || exit 1; done ;;
  attestation)
    subject=$3; bundle=; source=
    while [ $# -gt 0 ]; do
      case "$1" in --bundle) bundle=$2; shift ;; --source-digest) source=$2; shift ;; esac
      shift
    done
    [ "$(cat "$bundle")" = "attested $(sha "$subject") $source" ] || { echo "fake gh: attestation mismatch for $subject" >&2; exit 1; } ;;
  pr)
    case "$2" in list) ;; create) echo https://github.com/o/r/pull/1 ;; esac ;;
esac
exit 0
"#;

/// `mise` behind the fake for a prepare run: Rust comes from `mise.toml`,
/// `SANDBOX_RUST_BUMP` is what `mise upgrade --bump rust` moves it to, and
/// `SANDBOX_CARGO_UPGRADE_FAILS` makes `cargo upgrade` fail (a private git
/// source without its fetch credential).
pub(super) const PREPARE_MISE: &str = r#"#!/bin/sh
rust() { sed -n "s/^rust = [\"']\([^\"']*\)[\"']\$/\1/p" mise.toml; }
case "$*" in
  "ls --local --json")
    v=$(rust); printf '{"rust":[{"requested_version":"%s","version":"%s"}]}\n' "$v" "$v" ;;
  "upgrade --bump rust")
    if [ -n "${SANDBOX_RUST_BUMP:-}" ]; then
      sed "s/^rust = .*/rust = \"$SANDBOX_RUST_BUMP\"/" mise.toml > mise.toml.next && mv mise.toml.next mise.toml
    fi ;;
  "exec cargo:cargo-edit@"*) [ -z "${SANDBOX_CARGO_UPGRADE_FAILS:-}" ] || { echo "cargo upgrade: private source" >&2; exit 1; } ;;
esac
exit 0
"#;

/// Stand-in `velnor-actions`: `generate` writes the version's `ci.yml`;
/// releases after 0.1.0 also retire `retired.yml`.
pub(super) fn generator(version: &str) -> String {
    let retire = if version == "0.1.0" {
        ""
    } else {
        "rm -f .github/workflows/retired.yml\n"
    };
    format!(
        "#!/bin/sh\n[ \"$1\" = generate ] || exit 2\nmkdir -p .github/workflows\nprintf '# Generated by Velnor Actions %s\\nname: CI\\n' '{version}' > .github/workflows/ci.yml\n{retire}"
    )
}

/// Bytes `generate` of `version` writes to `ci.yml`.
pub(super) fn generated_ci(version: &str) -> String {
    format!("# Generated by Velnor Actions {version}\nname: CI\n")
}

pub(super) fn bare_git(dir: &Path, args: &[&str]) -> TestResult {
    let output = git_fixture::sterile_command()
        .current_dir(dir)
        .args(args)
        .output()?;
    if !output.status.success() {
        return Err(format!("git {args:?}: {}", String::from_utf8_lossy(&output.stderr)).into());
    }
    Ok(())
}

/// SHA-256 of a file through the platform tool the scripts use.
pub(super) fn sha256(path: &Path) -> TestResult<String> {
    let output = Command::new("sh")
        .arg("-c")
        .arg("if command -v sha256sum >/dev/null 2>&1; then sha256sum \"$1\"; else shasum -a 256 \"$1\"; fi")
        .arg("sh")
        .arg(path)
        .output()?;
    let text = String::from_utf8(output.stdout)?;
    let digest = text.split_whitespace().next().unwrap_or_default();
    if digest.len() != 64 {
        return Err(format!("sha256 of {}: {text}", path.display()).into());
    }
    Ok(digest.to_owned())
}

/// Combined stdout and stderr of a script run, for assertions.
pub(super) fn text(output: &Output) -> String {
    format!(
        "{}{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    )
}
