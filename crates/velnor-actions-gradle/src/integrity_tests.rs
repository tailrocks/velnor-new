//! Integrity check tests.

use super::*;

const HEX: &str = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";

fn metadata(verify: &str, artifact: &str, trust: &str) -> String {
    format!(
        "<?xml version=\"1.0\"?>\n<verification-metadata>\n<configuration>\n\
         <verify-metadata>{verify}</verify-metadata>\n<verify-signatures>false</verify-signatures>\n{trust}\
         </configuration>\n<components>\n<component group=\"g\" name=\"a\" version=\"1\">\n\
         <artifact name=\"a-1.jar\">\n{artifact}\n</artifact>\n</component>\n</components>\n\
         </verification-metadata>\n"
    )
}

#[test]
fn well_formed_metadata_passes() {
    let xml = metadata(
        "true",
        &format!("<sha256 value=\"{HEX}\" origin=\"Generated by Gradle\"/>"),
        "",
    );
    assert_eq!(
        check_verification(Some(&xml)),
        Vec::<IntegrityFinding>::new()
    );
}

#[test]
fn named_findings_for_bad_metadata() {
    assert_eq!(
        check_verification(None),
        [IntegrityFinding::VerificationMetadataMissing]
    );
    let sha = format!("<sha256 value=\"{HEX}\"/>");
    assert_eq!(
        check_verification(Some(&metadata("false", &sha, ""))),
        [IntegrityFinding::VerificationDisabled]
    );
    for weak in [
        "<md5 value=\"d41d8cd98f00b204e9800998ecf8427e\"/>",
        "<sha256 value=\"abc\"/>",
        "",
    ] {
        assert_eq!(
            check_verification(Some(&metadata("true", weak, ""))),
            [IntegrityFinding::VerificationNotSha256(
                "a-1.jar".to_owned()
            )],
            "{weak}"
        );
    }
    let broad = "<trusted-artifacts>\n<trust file=\".*\" regex=\"true\"/>\n</trusted-artifacts>\n";
    assert_eq!(
        check_verification(Some(&metadata("true", &sha, broad))),
        [IntegrityFinding::VerificationTrustTooBroad]
    );
    let scoped = "<trusted-artifacts>\n<trust group=\"com.chainargos\" regex=\"false\"/>\n</trusted-artifacts>\n";
    assert_eq!(
        check_verification(Some(&metadata("true", &sha, scoped))),
        Vec::<IntegrityFinding>::new()
    );
}

#[test]
fn locking_requires_a_lockfile_for_every_project_with_dependencies() {
    let projects = vec![
        (":a".to_owned(), "a".to_owned()),
        (":b".to_owned(), "b".to_owned()),
        (":c".to_owned(), "c".to_owned()),
    ];
    let files: BTreeSet<String> = [
        "a/build.gradle.kts",
        "a/gradle.lockfile",
        "b/build.gradle",
        "c/build.gradle.kts",
    ]
    .into_iter()
    .map(str::to_owned)
    .collect();
    let read = |path: &str| match path {
        "a/build.gradle.kts" | "c/build.gradle.kts" => {
            Some("plugins { }\ndependencies { api(x) }".to_owned())
        }
        "b/build.gradle" => Some("// dependencies {\napply plugin: 'java'".to_owned()),
        _ => None,
    };
    assert_eq!(
        check_locking(&projects, &files, &read),
        [IntegrityFinding::DependencyLockMissing(":c".to_owned())]
    );
    assert_eq!(
        IntegrityFinding::DependencyLockMissing(":c".to_owned()).code(),
        "gradle_dependency_lock_missing::c"
    );
    assert!(declares_dependencies("dependencies{}"));
    assert!(!declares_dependencies("val dependencies = 1"));
}
