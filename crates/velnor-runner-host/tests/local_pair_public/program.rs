#[derive(Clone, Copy)]
pub(crate) enum Program {
    /// Runs until SIGTERM, then exits 0: a runner whose job ends cleanly when
    /// the test sends the signal. Any other end (SIGKILL, a crash) is a failure.
    Sleep,
    Exit,
    Echo,
}

