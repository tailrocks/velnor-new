pub const RELEASE_HEADER: &str = "# Generated by velnor-gen. Change release-plz.toml or .velnor/release.toml and run `velnor-gen generate`.\n";

pub(crate) const LINT_IGNORE: &str = "jactionlint ignore=dangerous-triggers";
pub(crate) const ENVIRONMENT: &str = "release";
pub(crate) const HOSTED_RUNNER: &str = "ubuntu-latest";
const DEFAULT_BRANCH: &str = "${{ github.event.repository.default_branch }}";

pub(crate) const FROM_A_PASSED_PUSH: &str = "github.event.workflow_run.event == 'push' && github.event.workflow_run.conclusion == 'success' && github.event.workflow_run.head_branch == github.event.repository.default_branch";
pub(crate) const GATE_IS_READY: &str = "needs.gate.outputs.ready == 'true'";
const STILL_NEWEST: &str = "github.event.workflow_run.head_sha == github.sha";
const NEWEST_OUTPUT: &str = "steps.newest.outputs.newest == 'true'";
pub(crate) const VERIFIED_COMMIT: &str = "${{ github.event.workflow_run.head_sha }}";
const RELEASE_TIMEOUT_MINUTES: u16 = TAG_JOB_BASE_MINUTES;

pub fn render_release(
    plan: &ReleasePlan,
    helper: &HelperRelease,
    branch: &str,
    private: Option<&PrivateSources>,
) -> Result<BTreeMap<RepoPath, String>, Vec<RuleViolation>> {
    let source = source_of(plan);
    let mut collisions = output_collisions(plan, "tag");
    collisions.extend(dist_collisions(plan));
    if !collisions.is_empty() {
        return Err(collisions);
    }
    let mut jobs = vec![gate(plan, helper, &source)];
    if !source.tag_push {
        jobs.push(release_pr(plan, helper));
    }
    jobs.extend(tag_stage(plan));
    if !source.tag_push {
        jobs.push(tag(plan, helper));
    }
    jobs.extend(match &plan.family {
        Some(family) => family_jobs(plan, family, helper, private),
        None => binary_jobs(plan, helper, private),
    });
    jobs.extend(publish_stage(plan));
    jobs.extend(finalize_job(plan, helper));
    let jobs = jobs
        .into_iter()
        .map(crate::mise_digest::pin_to_runner_platform);
    let rendered = RenderedWorkflow {
        jobs: jobs.collect(),
    };
    check_rules(&rendered)?;
    let workflow = [
        entry("name", text("Release")),
        entry("on", trigger(plan, branch, &source)),
        entry("permissions", Yaml::Map(Vec::new())),
        entry(
            "concurrency",
            Yaml::Map(vec![
                entry(
                    "group",
                    Yaml::Expr(format!(
                        "release-{}",
                        if source.tag_push {
                            "${{ github.sha }}"
                        } else {
                            "${{ github.event.workflow_run.head_sha }}"
                        }
                    )),
                ),
                entry("cancel-in-progress", Yaml::Bool(false)),
            ]),
        ),
        entry(
            "jobs",
            Yaml::Map(
                rendered
                    .jobs
                    .iter()
                    .map(|job| (job.id.clone(), yaml_job(job, ShellcheckMarks::Jobs)))
                    .collect(),
            ),
        ),
    ];
    let file = crate::seal(RELEASE_HEADER, &emit(&workflow));
    if file.len() > MAX_WORKFLOW_BYTES {
        return Err(vec![crate::rule_messages::size_report::too_large(
            RELEASE_WORKFLOW_PATH.as_str(),
            file.len(),
            &rendered.jobs,
        )]);
    }
    Ok(BTreeMap::from([(RELEASE_WORKFLOW_PATH, file)]))
}

fn trigger(plan: &ReleasePlan, branch: &str, source: &Source) -> Yaml {
    let names = |items: &[&str]| Yaml::Seq(items.iter().map(|item| text(item)).collect());
    if let (true, Some(family)) = (source.tag_push, &plan.family) {
        let (before, after) = family.tag_affixes();
        let glob = format!("{}*{}", escape_filter(&before), escape_filter(&after));
        return Yaml::Map(vec![entry(
            "push",
            Yaml::Map(vec![entry("tags", names(&[&glob]))]),
        )]);
    }
    let after: Vec<String> = plan.after.iter().map(|name| escape_filter(name)).collect();
    let after: Vec<&str> = after.iter().map(String::as_str).collect();
    Yaml::Map(vec![entry(
        "workflow_run",
        Yaml::Noted(
            LINT_IGNORE.to_owned(),
            Box::new(Yaml::Map(vec![
                entry("workflows", names(&after)),
                entry("types", names(&["completed"])),
                entry("branches", names(&[&escape_filter(branch)])),
            ])),
        ),
    )])
}

fn escape_filter(name: &str) -> String {
    name.chars()
        .flat_map(|ch| {
            let escaped = matches!(ch, '\\' | '*' | '?' | '+' | '[' | ']' | '!');
            escaped.then_some('\\').into_iter().chain([ch])
        })
        .collect()
}

pub(crate) fn after_the_gate(id: &str) -> RenderedJob {
    after_the_gate_with(id, FROM_A_PASSED_PUSH)
}

pub(crate) fn after_the_gate_with(id: &str, passed: &str) -> RenderedJob {
    RenderedJob {
        id: id.to_owned(),
        needs: vec!["gate".to_owned()],
        condition: Some(expression(&format!("{GATE_IS_READY} && {passed}"))),
        environment: Some(ENVIRONMENT.to_owned()),
        runs_on: HOSTED_RUNNER.to_owned(),
        timeout_minutes: RELEASE_TIMEOUT_MINUTES,
        ..RenderedJob::default()
    }
}

fn release_pr(plan: &ReleasePlan, helper: &HelperRelease) -> RenderedJob {
    let mut steps = install_release_plz(plan);
    steps.push(install_helper(helper));
    steps.push(checkout(VERIFIED_COMMIT, 0));
    steps.push(newest_check());
    steps.push(on_the_default_branch());
    steps.push(refuse_commands(&plan.roots, false));
    steps.push(app_token(&[
        ("contents", "write"),
        ("pull-requests", "write"),
    ]));
    steps.extend(plan.roots.iter().map(|root| {
        release_plz_step(
            format!("Open the release pull request of {}", label(root)),
            &format!("release-plz release-pr {}", release_plz_arguments(root)),
        )
    }));
    only_while_newest(&mut steps);
    RenderedJob {
        condition: Some(expression(&format!(
            "{GATE_IS_READY} && {FROM_A_PASSED_PUSH} && {STILL_NEWEST}"
        ))),
        permissions: permissions(&[("contents", "read")]),
        concurrency: Some(RenderedConcurrency {
            group: "release-pr".to_owned(),
            cancel_in_progress: false,
        }),
        steps,
        ..after_the_gate("release-pr")
    }
}

pub(crate) fn only_while_newest(steps: &mut [RenderedStep]) {
    let after_newest = steps
        .iter()
        .position(|step| step.id.as_deref() == Some("newest"))
        .map_or(0, |index| index + 1);
    for step in &mut steps[after_newest..] {
        step.condition = Some(expression(NEWEST_OUTPUT));
    }
}

fn tag(plan: &ReleasePlan, helper: &HelperRelease) -> RenderedJob {
    let mut steps = install_release_plz(plan);
    steps.push(install_helper(helper));
    steps.push(checkout(VERIFIED_COMMIT, 0));
    steps.push(newest_check());
    steps.push(refuse_commands(&plan.roots, true));
    steps.push(source_preflight(plan));
    steps.push(app_token(&[
        ("contents", "write"),
        ("pull-requests", "read"),
    ]));
    let files: Vec<String> = (0..plan.roots.len())
        .map(|index| format!("\"$RUNNER_TEMP/release-{index}.json\""))
        .collect();
    steps.extend(plan.roots.iter().zip(&files).map(|(root, file)| {
        release_plz_step(
            format!("Tag the releases of {}", label(root)),
            &format!(
                "release-plz release {} -o json > {file}",
                release_plz_arguments(root)
            ),
        )
    }));
    steps.push(record(plan, helper, &files));
    only_while_newest(&mut steps);
    let mut scopes = vec![("contents", "read"), ("pull-requests", "read")];
    if plan.roots.iter().any(|root| root.publishes_to_crates_io) {
        scopes.push(("id-token", "write"));
    }
    RenderedJob {
        concurrency: Some(RenderedConcurrency {
            group: "release-tag".to_owned(),
            cancel_in_progress: false,
        }),
        permissions: permissions(&scopes),
        outputs: plan
            .tagged_binaries()
            .iter()
            .map(|binary| binary.package.clone())
            .chain(without_binary(plan))
            .map(|package| {
                let output = format!("${{{{ steps.record.outputs.{package} }}}}");
                (package, output)
            })
            .chain(commit_outputs(plan))
            .collect(),
        needs: [String::from("gate")]
            .into_iter()
            .chain(tag_needs(plan))
            .collect(),
        timeout_minutes: u16::try_from(
            u64::from(TAG_JOB_BASE_MINUTES).saturating_add(publish_budget_minutes(&plan.roots)),
        )
        .unwrap_or(u16::MAX),
        steps,
        ..after_the_gate("tag")
    }
}

fn source_preflight(plan: &ReleasePlan) -> RenderedStep {
    let prefixes = plan
        .roots
        .iter()
        .map(|root| format!("--branch-prefix={}", shell_word(&root.pr_branch_prefix)))
        .collect::<Vec<_>>()
        .join(" ");
    RenderedStep {
        name: "Check that release-plz would tag the verified commit".to_owned(),
        env: variables(&[
            ("GITHUB_TOKEN", "${{ github.token }}"),
            ("REPOSITORY", "${{ github.repository }}"),
            ("COMMIT", VERIFIED_COMMIT),
        ]),
        run: Some(format!(
            "velnor-ci release preflight --repo=\"$REPOSITORY\" --verified-commit=\"$COMMIT\" {prefixes}"
        )),
        ..RenderedStep::default()
    }
}

fn record(plan: &ReleasePlan, helper: &HelperRelease, files: &[String]) -> RenderedStep {
    let files = files.join(" ");
    let recovers = helper.version().at_least(RECORD_RECOVERY_HELPER);
    let mut env = variables(&[
        ("GITHUB_TOKEN", "${{ github.token }}"),
        ("REPOSITORY", "${{ github.repository }}"),
        ("COMMIT", VERIFIED_COMMIT),
    ]);
    let mut run =
        "velnor-ci release record --repo=\"$REPOSITORY\" --verified-commit=\"$COMMIT\"".to_owned();
    if recovers {
        env.push((
            "RUSTUP_TOOLCHAIN".to_owned(),
            Value::Text(TOOLCHAIN.to_owned()),
        ));
        run = format!("{run} --app={RELEASE_APP_SLUG} {}", record_configs(plan));
    }
    if helper.version().at_least(RECORD_GROUPS_HELPER) {
        for root in plan
            .roots
            .iter()
            .filter(|root| !root.version_groups.is_empty())
        {
            let file = shell_word(&join(&root.root, RELEASE_PLZ_FILE));
            run = format!("{run} --version-groups={file}");
        }
    }
    RenderedStep {
        id: Some("record".to_owned()),
        name: "Record the released packages and the commits their tags are on".to_owned(),
        env,
        run: Some(format!("{run} {files}")),
        ..RenderedStep::default()
    }
}

fn record_configs(plan: &ReleasePlan) -> String {
    plan.roots
        .iter()
        .map(|root| {
            format!(
                "--config={}",
                shell_word(&join(&root.root, RELEASE_PLZ_FILE))
            )
        })
        .collect::<Vec<_>>()
        .join(" ")
}

pub(crate) fn newest_check() -> RenderedStep {
    RenderedStep {
        id: Some("newest".to_owned()),
        name: "Check that the verified commit is still the newest on the default branch".to_owned(),
        env: variables(&[
            ("GH_TOKEN", "${{ github.token }}"),
            ("REPOSITORY", "${{ github.repository }}"),
            ("COMMIT", VERIFIED_COMMIT),
            ("BRANCH", DEFAULT_BRANCH),
        ]),
        run: Some(
            "gh api \"repos/$REPOSITORY/git/ref/heads/$BRANCH\" --jq '\"newest=\\(.object.sha == env.COMMIT)\"' >> \"$GITHUB_OUTPUT\""
                .to_owned(),
        ),
        ..RenderedStep::default()
    }
}

fn on_the_default_branch() -> RenderedStep {
    RenderedStep {
        name: "Move the verified commit onto the default branch".to_owned(),
        env: variables(&[("BRANCH", DEFAULT_BRANCH)]),
        run: Some("git switch --force-create \"$BRANCH\"".to_owned()),
        ..RenderedStep::default()
    }
}
