use std::fs;
use std::path::Path;

use super::prepare::{Setup, output, prepare, reported};

const REGISTRY: &str = "registry+https://github.com/rust-lang/crates.io-index";

struct Package<'a> {
    name: &'a str,
    version: &'a str,
    registry: bool,
    dependencies: &'a [&'a str],
}

fn entry(package: &Package<'_>) -> String {
    let source = if package.registry {
        format!(
            "source = \"{REGISTRY}\"\nchecksum = \"{}\"\n",
            "ab".repeat(32)
        )
    } else {
        String::new()
    };
    let dependencies = if package.dependencies.is_empty() {
        String::new()
    } else {
        let listed: Vec<String> = package
            .dependencies
            .iter()
            .map(|dependency| format!("\"{dependency}\""))
            .collect();
        format!("dependencies = [{}]\n", listed.join(", "))
    };
    format!(
        "\n[[package]]\nname = \"{}\"\nversion = \"{}\"\n{source}{dependencies}",
        package.name, package.version
    )
}

fn lock(packages: &[Package<'_>]) -> String {
    let entries: Vec<String> = packages.iter().map(entry).collect();
    format!(
        "# This file is automatically @generated by Cargo.\nversion = 4\n{}",
        entries.concat()
    )
}

fn member<'a>(name: &'a str, version: &'a str, dependencies: &'a [&'a str]) -> Package<'a> {
    Package {
        name,
        version,
        registry: false,
        dependencies,
    }
}

fn registry<'a>(name: &'a str, version: &'a str) -> Package<'a> {
    Package {
        name,
        version,
        registry: true,
        dependencies: &[],
    }
}

fn members_of(members: &[&str]) -> String {
    let listed: Vec<String> = members
        .iter()
        .map(|name| {
            format!(
                "{{\"name\":\"{name}\",\"manifest\":\"{name}/Cargo.toml\",\"dependencies\":[],\"targets\":[]}}"
            )
        })
        .collect();
    format!("{{\"members\":[{}]}}", listed.join(","))
}

fn metadata(members: &[&str], other_root: &[&str]) -> String {
    format!(
        "{{\"roots\":{{\"Cargo.toml\":{},\"other/Cargo.toml\":{}}},\"manifests\":{{}},\"layout\":\"\"}}",
        members_of(members),
        members_of(other_root)
    )
}

fn key(lock_text: &str, members: &[&str]) -> String {
    key_in(lock_text, members, &[])
}

fn key_in(lock_text: &str, members: &[&str], other_root: &[&str]) -> String {
    let (lock_text, metadata) = (lock_text.to_owned(), metadata(members, other_root));
    let mut setup = Setup::new(reported("1.99.1", Some("0.9.151")));
    setup.populate = Some(Box::new(move |checkout: &Path| {
        fs::write(checkout.join("Cargo.lock"), &lock_text).unwrap_or_else(|e| unreachable!("{e}"));
        fs::write(checkout.join(".velnor/rust-metadata.json"), &metadata)
            .unwrap_or_else(|e| unreachable!("{e}"));
    }));
    let run = prepare("lock-key", &setup);
    assert!(run.output.status.success(), "{:?}", run.output);
    let digest = output(&run, "lock_root").to_owned();
    assert_eq!(digest.len(), 64, "{}", run.outputs);
    assert!(digest.bytes().all(|byte| byte.is_ascii_hexdigit()));
    digest
}

fn workspace(version: &'static str, registry_version: &'static str) -> String {
    lock(&[
        member("app", version, &["core", "serde"]),
        member("core", version, &["serde"]),
        registry("serde", registry_version),
    ])
}

#[test]
fn a_member_version_bump_keeps_the_lock_key() {
    let members = ["app", "core"];
    let before = key(&workspace("0.1.83", "1.0.229"), &members);
    let after = key(&workspace("0.1.85", "1.0.229"), &members);
    assert_eq!(before, after);
}

#[test]
fn a_registry_version_change_moves_the_lock_key() {
    let members = ["app", "core"];
    assert_ne!(
        key(&workspace("0.1.83", "1.0.229"), &members),
        key(&workspace("0.1.83", "1.0.230"), &members)
    );
}

#[test]
fn a_registry_version_change_during_a_bump_moves_the_lock_key() {
    let members = ["app", "core"];
    assert_ne!(
        key(&workspace("0.1.83", "1.0.229"), &members),
        key(&workspace("0.1.85", "1.0.230"), &members)
    );
}

#[test]
fn a_new_dependency_moves_the_lock_key() {
    let members = ["app", "core"];
    let with = lock(&[
        member("app", "0.1.83", &["core", "serde", "url"]),
        member("core", "0.1.83", &["serde"]),
        registry("serde", "1.0.229"),
        registry("url", "2.5.8"),
    ]);
    assert_ne!(
        key(&workspace("0.1.83", "1.0.229"), &members),
        key(&with, &members)
    );
}

#[test]
fn a_feature_that_adds_a_locked_package_moves_the_lock_key() {
    let members = ["app", "core"];
    let derived = lock(&[
        member("app", "0.1.83", &["core", "serde"]),
        member("core", "0.1.83", &["serde"]),
        registry("serde", "1.0.229"),
        registry("serde_derive", "1.0.229"),
    ]);
    assert_ne!(
        key(&workspace("0.1.83", "1.0.229"), &members),
        key(&derived, &members)
    );
}

#[test]
fn the_version_of_a_path_package_outside_the_workspace_stays_in_the_lock_key() {
    let members = ["app"];
    let outside = |version: &'static str| {
        lock(&[
            member("app", "0.1.83", &["shared"]),
            member("shared", version, &[]),
        ])
    };
    assert_ne!(
        key(&outside("1.0.0"), &members),
        key(&outside("1.0.1"), &members)
    );
}

#[test]
fn a_member_of_another_root_of_the_repository_counts_as_a_member() {
    let shared = |version: &'static str| {
        lock(&[
            member("app", "0.1.83", &["shared"]),
            member("shared", version, &[]),
        ])
    };
    assert_eq!(
        key_in(&shared("1.0.0"), &["app"], &["shared"]),
        key_in(&shared("1.0.1"), &["app"], &["shared"])
    );
    assert_ne!(
        key_in(&shared("1.0.0"), &["app"], &[]),
        key_in(&shared("1.0.1"), &["app"], &[])
    );
}

#[test]
fn a_member_that_shares_its_name_with_a_registry_package_keeps_its_version() {
    let members = ["serde"];
    let shared = |version: &'static str| {
        lock(&[member("serde", version, &[]), registry("serde", "1.0.229")])
    };
    assert_ne!(
        key(&shared("0.1.0"), &members),
        key(&shared("0.1.1"), &members)
    );
}

#[test]
fn a_lock_that_does_not_parse_is_keyed_by_its_bytes() {
    let members = ["app"];
    let broken = |tail: &str| {
        format!("version = 4\n[[package]\nname = \"app\"\nversion = \"0.1.83\"\n{tail}")
    };
    let first = key(&broken(""), &members);
    assert_eq!(first, key(&broken(""), &members));
    assert_ne!(first, key(&broken("# edit\n"), &members));
}

#[test]
fn a_member_the_metadata_does_not_list_keeps_its_version() {
    let listed = key(&workspace("0.1.83", "1.0.229"), &["app", "core"]);
    let unlisted = key(&workspace("0.1.85", "1.0.229"), &["app"]);
    assert_ne!(listed, unlisted);
}

fn legacy_workspace(root_version: &'static str, registry_version: &'static str) -> String {
    format!(
        "[root]\nname = \"app\"\nversion = \"{root_version}\"\ndependencies = [\"serde\"]\n{}",
        entry(&registry("serde", registry_version))
    )
}

