//! Deterministic actionlint.yaml generator cases.
use velnor_actions_actionlint::{
    ActionlintCapabilities, ActionlintConfigInput, ActionlintError, IgnoreEntry, IgnorePolicy,
    config::{ZizmorConfigInput, ZizmorWorkflowText, render_zizmor_yaml},
    render_actionlint_yaml,
};

/// Default bytes from the generated-file contract template.
const DEFAULT_YAML: &str = "# Generated by Velnor Actions 0.1.0; edit .velnor/config.toml and regenerate.\n\nconfig-variables: []\n\nself-hosted-runner:\n  labels:\n    - ubuntu-26.04\n";

/// Sample generated workflow path shared by config cases.
const WORKFLOW: &str = ".github/workflows/velnor.yml";

fn narrow_ignore() -> IgnoreEntry {
    IgnoreEntry {
        rule: "shellcheck".to_owned(),
        path: WORKFLOW.to_owned(),
        justification: "approved SC2086 for quoted matrix expansion".to_owned(),
    }
}

#[test]
fn default_bytes_match_spec_template() {
    let input = ActionlintConfigInput::new("0.1.0");
    assert_eq!(
        render_actionlint_yaml(&input).map(|output| output.yaml),
        Ok(DEFAULT_YAML.to_owned())
    );
}

#[test]
fn config_bytes_are_deterministic() {
    let first = ActionlintConfigInput::new("0.1.0")
        .with_config_variable("ZULU")
        .with_config_variable("ALPHA")
        .with_config_variable("ALPHA");
    let second = ActionlintConfigInput::new("0.1.0")
        .with_config_variable("ALPHA")
        .with_config_variable("ZULU");
    let first_yaml = render_actionlint_yaml(&first).map(|output| output.yaml);
    let second_yaml = render_actionlint_yaml(&second).map(|output| output.yaml);
    assert!(first_yaml.is_ok());
    assert_eq!(first_yaml, second_yaml);
}

