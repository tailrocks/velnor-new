#[test]
fn config_variables_emit_exact_declared_set() {
    let input = ActionlintConfigInput::new("0.1.0")
        .with_config_variable("ZULU")
        .with_config_variable("ALPHA")
        .with_config_variable("ZULU");
    let output = render_actionlint_yaml(&input).expect("renders");
    let mut in_variables = false;
    let mut rendered = Vec::new();
    for line in output.yaml.lines() {
        if line == "config-variables:" {
            in_variables = true;
            continue;
        }
        if in_variables {
            if let Some(name) = line.strip_prefix("  - ") {
                rendered.push(name.to_owned());
            } else {
                break;
            }
        }
    }
    assert_eq!(rendered, vec!["ALPHA".to_owned(), "ZULU".to_owned()]);
    let empty = render_actionlint_yaml(&ActionlintConfigInput::new("0.1.0")).expect("renders");
    assert!(empty.yaml.contains("config-variables: []"));
}

/// Filesystem/process/network tokens that must never appear in config sources.
const FORBIDDEN_TOKENS: &[&str] = &[
    "init-config",
    "Command",
    "std::process",
    "reqwest",
    "ureq",
    "fetch(",
    "fetch_",
    "from_url",
    "Url::",
    "download(",
    "TcpStream",
];

#[test]
fn config_render_never_inits_or_fetches() {
    let src = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src");
    let entries = std::fs::read_dir(&src).expect("src readable");
    let mut checked = 0;
    for entry in entries {
        let path = entry.expect("entry readable").path();
        if path.extension().is_none_or(|ext| ext != "rs") {
            continue;
        }
        let text = std::fs::read_to_string(&path).expect("source readable");
        checked += 1;
        let code: String = text
            .lines()
            .map(|line| line.split("//").next().unwrap_or_default())
            .collect::<Vec<_>>()
            .join("\n");
        for token in FORBIDDEN_TOKENS {
            assert!(
                !code.contains(token),
                "forbidden token {token} in {}",
                path.display()
            );
        }
    }
    assert!(checked > 0, "at least one source file must be scanned");
}

