#[test]
fn zizmor_bytes_deterministic_across_workflow_order() {
    let blessed = ZizmorWorkflowText {
        path: WORKFLOW.to_owned(),
        text: blessed_text(),
    };
    let other = ZizmorWorkflowText {
        path: ".github/workflows/other.yml".to_owned(),
        text: "name: Other\n".to_owned(),
    };
    let first = ZizmorConfigInput {
        generator_version: "0.1.0".to_owned(),
        workflows: vec![blessed.clone(), other.clone()],
    };
    let second = ZizmorConfigInput {
        generator_version: "0.1.0".to_owned(),
        workflows: vec![other, blessed],
    };
    let first_yaml = render_zizmor_yaml(&first).map(|output| output.yaml);
    let second_yaml = render_zizmor_yaml(&second).map(|output| output.yaml);
    assert!(first_yaml.is_ok());
    assert_eq!(first_yaml, second_yaml);
}

