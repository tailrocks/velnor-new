/// Workflow text with the blessed tag on line 3, ref at column 15.
fn blessed_text() -> String {
    "# Generated by Velnor Actions 0.1.0 - DO NOT EDIT\nname: CI\n        uses: asamarts/alint@v0.16.1 # v0.16.1\n"
        .to_owned()
}

fn zizmor_input(text: &str) -> ZizmorConfigInput {
    ZizmorConfigInput {
        generator_version: "0.1.0".to_owned(),
        workflows: vec![ZizmorWorkflowText {
            path: WORKFLOW.to_owned(),
            text: text.to_owned(),
        }],
    }
}

#[test]
fn zizmor_blessed_tag_ignores_exact_location() {
    let output = render_zizmor_yaml(&zizmor_input(&blessed_text()));
    assert_eq!(
        output.map(|output| output.approved_ignores),
        Ok(vec!["velnor.yml:3:15".to_owned()])
    );
}

#[test]
fn zizmor_bytes_match_template_with_policy_citation() {
    let expected = "# Generated by Velnor Actions 0.1.0 for staged zizmor validation; never commit.\n# Version-policy exception (docs/proposed/version-policy.md §2): exactly\n# uses asamarts/alint@v0.16.1 may stay tag-pinned; every\n# other ref still requires a hash (implicit \"*\": hash-pin).\nrules:\n  unpinned-uses:\n    ignore:\n      - velnor.yml:3:15  # expires: alint reviewed-tag exception review (version-policy §2)\n";
    assert_eq!(
        render_zizmor_yaml(&zizmor_input(&blessed_text())).map(|output| output.yaml),
        Ok(expected.to_owned())
    );
}

#[test]
fn zizmor_ignores_carry_expiry_comments() {
    let output = render_zizmor_yaml(&zizmor_input(&blessed_text())).expect("renders");
    assert!(!output.approved_ignores.is_empty());
    let mut entries = 0;
    for line in output.yaml.lines() {
        if !line.starts_with("      - ") {
            continue;
        }
        entries += 1;
        assert!(line.contains("# expires:"), "ignore without expiry: {line}");
    }
    assert_eq!(entries, output.approved_ignores.len());
    for rule in &output.approved_ignores {
        let parts: Vec<&str> = rule.split(':').collect();
        assert_eq!(parts.len(), 3, "narrow file:line:col: {rule}");
        assert!(parts[1].chars().all(|c| c.is_ascii_digit()));
        assert!(parts[2].chars().all(|c| c.is_ascii_digit()));
    }
}

