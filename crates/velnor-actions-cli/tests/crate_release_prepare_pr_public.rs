use std::{fs, path::Path, process::Command};

fn git(root: &Path, args: &[&str]) -> Result<String, Box<dyn std::error::Error>> {
    let output = Command::new("git").current_dir(root).args(args).output()?;
    if !output.status.success() {
        return Err("fixture git failed".into());
    }
    Ok(String::from_utf8(output.stdout)?.trim().to_owned())
}

struct Fixture {
    temp: tempfile::TempDir,
    source: std::path::PathBuf,
    runner: std::path::PathBuf,
    intent: String,
    intent_path: std::path::PathBuf,
    sha: String,
}

fn fixture() -> Result<Fixture, Box<dyn std::error::Error>> {
    let temp = tempfile::tempdir()?;
    let source = temp.path().join("source");
    let runner = temp.path().join("runner");
    fs::create_dir_all(source.join(".github"))?;
    fs::create_dir(&runner)?;
    fs::write(
        source.join("Cargo.toml"),
        "[package]\nname = 'demo'\nversion = '0.1.0'\n",
    )?;
    fs::write(
        source.join(".github/release-plz.toml"),
        format!(
            "# Generated by Velnor Actions {}; edit .velnor/config.toml and regenerate.\n[workspace]\nrelease = false\nrelease_always = false\nsemver_check = true\npublish_no_verify = false\npublish_allow_dirty = false\ngit_tag_name = \"{{{{ package }}}}-v{{{{ version }}}}\"\n\n[[package]]\nname = \"demo\"\nrelease = true\npublish = true\ngit_only = false\n",
            env!("CARGO_PKG_VERSION")
        ),
    )?;
    let intent = format!(
        r#"schema = 1
repository = "example/demo"
default_branch = "main"
environment = "release"
required_workflow_path = ".github/workflows/ci.yml"
trusted_reviewer_id = 1
rust_version = "1.99.1"
generator_version = "{}"
generator_source_sha = "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb"
generator_manifest_sha256 = "cccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccc"
release_plz_version = "0.4.3"
runner = "ubuntu-24.04"
authentication = "trusted-publishing"
manifest_path = "Cargo.toml"
pr_write_paths = ["Cargo.toml"]
registry = "crates-io"
packages = ["demo"]
tag_template = "{{{{ package }}}}-v{{{{ version }}}}"
[publish_features]
demo = []
"#,
        env!("CARGO_PKG_VERSION")
    );
    let intent_path = source.join(".github/velnor-release-intent.toml");
    fs::write(&intent_path, &intent)?;
    git(&source, &["init", "-q"])?;
    git(&source, &["add", "."])?;
    git(
        &source,
        &[
            "-c",
            "user.name=Fixture",
            "-c",
            "user.email=fixture@example.invalid",
            "-c",
            "commit.gpgsign=false",
            "commit",
            "-qm",
            "fixture",
        ],
    )?;
    let sha = git(&source, &["rev-parse", "HEAD"])?;
    Ok(Fixture {
        temp,
        source,
        runner,
        intent,
        intent_path,
        sha,
    })
}

#[test]
fn prepare_pr_rejects_unapproved_inputs_without_output() -> Result<(), Box<dyn std::error::Error>> {
    let Fixture {
        temp,
        source,
        runner,
        intent,
        intent_path,
        sha,
    } = fixture()?;
    let output_file = runner.join("github-output");
    for (key, value) in [
        ("GITHUB_EVENT_NAME", "workflow_dispatch"),
        ("GITHUB_REPOSITORY", "other/demo"),
        ("GITHUB_REF", "refs/heads/other"),
        ("GITHUB_RUN_ATTEMPT", "2"),
        ("GITHUB_RUN_ID", "invalid"),
        ("NO_RUN_ID", "unused"),
        ("INVALID_INTENT", "unused"),
        ("GITHUB_SHA", "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"),
        ("NO_OVERRIDE", "unused"),
    ] {
        fs::write(&output_file, "")?;
        let mut command = Command::new(env!("CARGO_BIN_EXE_velnor-actions"));
        command
            .args(["crate-release", "prepare-pr"])
            .env_clear()
            .env("PATH", "/usr/bin:/bin")
            .env("HOME", temp.path())
            .env("GITHUB_WORKSPACE", &source)
            .env("RUNNER_TEMP", &runner)
            .env("GITHUB_REPOSITORY", "example/demo")
            .env("GITHUB_EVENT_NAME", "push")
            .env("GITHUB_REF", "refs/heads/main")
            .env("GITHUB_RUN_ID", "123")
            .env("GITHUB_RUN_ATTEMPT", "1")
            .env("GITHUB_SHA", &sha)
            .env("GITHUB_OUTPUT", &output_file);
        if key == "NO_RUN_ID" {
            command.env_remove("GITHUB_RUN_ID");
        } else if key == "INVALID_INTENT" {
            fs::write(&intent_path, "invalid")?;
        } else if key != "NO_OVERRIDE" {
            command.env(key, value);
        }
        let result = command.output()?;
        if key == "INVALID_INTENT" {
            fs::write(&intent_path, &intent)?;
        }
        let expected = "release_pr_preparation_invalid";
        assert!(
            String::from_utf8_lossy(&result.stderr).contains(expected),
            "wrong failure for {key}"
        );
        assert!(!result.status.success(), "unexpectedly accepted {key}");
        assert_eq!(fs::read(&output_file)?, Vec::<u8>::new());
        assert!(!runner.join("velnor-release-pr-preparation.json").exists());
    }
    Ok(())
}

#[test]
fn prepare_pr_rejects_changed_generated_config() -> Result<(), Box<dyn std::error::Error>> {
    let Fixture {
        temp,
        source,
        runner,
        ..
    } = fixture()?;
    fs::write(
        source.join(".github/release-plz.toml"),
        "[workspace]\nsemver_check = false\n",
    )?;
    git(&source, &["add", ".github/release-plz.toml"])?;
    git(
        &source,
        &[
            "-c",
            "user.name=Fixture",
            "-c",
            "user.email=fixture@example.invalid",
            "-c",
            "commit.gpgsign=false",
            "commit",
            "-qm",
            "alter config",
        ],
    )?;
    let sha = git(&source, &["rev-parse", "HEAD"])?;
    let output_file = runner.join("github-output");
    fs::write(&output_file, "")?;
    let result = Command::new(env!("CARGO_BIN_EXE_velnor-actions"))
        .args(["crate-release", "prepare-pr"])
        .env_clear()
        .env("PATH", "/usr/bin:/bin")
        .env("HOME", temp.path())
        .env("GITHUB_WORKSPACE", &source)
        .env("RUNNER_TEMP", &runner)
        .env("GITHUB_REPOSITORY", "example/demo")
        .env("GITHUB_EVENT_NAME", "push")
        .env("GITHUB_REF", "refs/heads/main")
        .env("GITHUB_RUN_ID", "123")
        .env("GITHUB_RUN_ATTEMPT", "1")
        .env("GITHUB_SHA", sha)
        .env("GITHUB_OUTPUT", &output_file)
        .output()?;
    assert!(!result.status.success());
    assert!(
        String::from_utf8_lossy(&result.stderr).contains("release_pr_generated_config_mismatch")
    );
    assert_eq!(fs::read(&output_file)?, Vec::<u8>::new());
    assert!(!runner.join("velnor-release-pr-preparation.json").exists());
    Ok(())
}
