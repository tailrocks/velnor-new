//! Gap C cases: marker compatibility, durability, declarations, conflicts.
use velnor_actions_rust::{
    CompileDriver, EvidenceFile, PROFILE_CONFLICT_CODE, ProfileError, ProfileInputs, ProfileSource,
    TRANSIENT_EVIDENCE_CODE, TestRunner, detect_profile, is_generated_output,
};

/// Wrap `content` read from `path` as evidence input.
fn file<'a>(path: &'a str, content: &'a str) -> EvidenceFile<'a> {
    EvidenceFile { path, content }
}

/// Generated body invoking both MBX and Nextest under `marker`.
fn generated(marker: &str) -> String {
    format!("{marker}\nrun: mbx clippy --package a\nrun: cargo nextest run\n")
}

#[test]
fn old_marker_output_is_never_evidence() {
    let content = generated("# Generated by velnor-actions 0.1.0 - DO NOT EDIT");
    assert!(is_generated_output(&content));
    let inputs = ProfileInputs {
        handwritten_workflows: vec![file(".github/workflows/ci.yml", &content)],
        ..ProfileInputs::default()
    };
    let Ok(outcome) = detect_profile(&inputs) else {
        panic!("old-marker output must fall back to defaults");
    };
    assert_eq!(outcome.profile.compile_driver, CompileDriver::Cargo);
    assert_eq!(outcome.profile.test_runner, TestRunner::CargoTest);
    assert_eq!(
        outcome.profile.evidence,
        [] as [velnor_actions_rust::Evidence; 0]
    );
    assert_eq!(
        outcome.findings,
        [] as [velnor_actions_rust::ProfileFinding; 0]
    );
}

