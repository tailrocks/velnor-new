#!/bin/bash
set -euo pipefail
root=/root/Projects/tailrocks/velnor-project/velnor-new
out=/root/velnor-stop-preservation-20261005
cd "$root"
while read -r sha; do
  branch="preservation/stop-20261005/reflog/$sha"
  git push origin "$sha:refs/heads/$branch" >> "$out/push-extra.log" 2>&1
  actual=$(git ls-remote origin "refs/heads/$branch" | cut -f1)
  [ "$actual" = "$sha" ] || exit 1
  printf '%s\t%s\treflog\n' "$sha" "$branch" >> "$out/preserved-refs.tsv"
done < "$out/local-only-commits"
while IFS=$'\t' read -r p head n remote; do
  id=$(printf '%s' "$p" | sha256sum | cut -c1-12)
  case "$remote" in *tailrocks/velnor-new*) ;; *) continue;; esac
  git -C "$p" status --porcelain > "$out/clone-status-$id"
  git -C "$p" for-each-ref --format='%(objectname) %(refname)' refs/heads refs/stash > "$out/clone-refs-$id"
  # Clone source/output is preserved unchanged; generated bytecode is omitted.
  if [ "$n" -gt 0 ]; then
    if git -C "$p" ls-files -m -o --exclude-standard -z | while IFS= read -r -d '' f; do [ ! -f "$p/$f" ] || rg -Il -- '(gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{30,}|AKIA[0-9A-Z]{16}|-----BEGIN (RSA |EC |OPENSSH )?PRIVATE KEY-----)' "$p/$f"; done > "$out/clone-secrets-$id"; then :; fi
    if [ -s "$out/clone-secrets-$id" ]; then printf 'held secrets\t%s\n' "$p" >> "$out/exceptions"; continue; fi
    git -C "$p" add -A -- . ':!scripts/__pycache__' ':!.velnor/archive-guard'
    if ! git -C "$p" diff --cached --quiet; then
      git -C "$p" -c user.name='Alexey Zhokhov' -c user.email='alexey@zhokhov.com' -c core.hooksPath=/dev/null -c commit.gpgsign=false commit -m 'WIP: preserve existing temporary-clone state at stop [skip ci]' -m 'Co-authored-by: Codex <codex@openai.com>' -m 'Signed-off-by: Alexey Zhokhov <alexey@zhokhov.com>' > "$out/clone-commit-$id.log"
    fi
  fi
  [ -n "$(git -C "$p" rev-parse --verify HEAD 2>/dev/null || true)" ] || continue
  # Preserve every local branch plus current detached HEAD and stashes.
  git -C "$p" for-each-ref --format='%(objectname) %(refname)' refs/heads refs/stash > "$out/clone-refs-$id"
  printf '%s HEAD\n' "$(git -C "$p" rev-parse HEAD)" >> "$out/clone-refs-$id"
  while read -r sha ref; do
    name=${ref#refs/}; branch="preservation/stop-20261005/clones/$id/$name"
    git -C "$p" -c credential.helper= -c credential.helper="!/root/.local/share/mise/installs/github-cli-cli/2.102.0/bin/gh auth git-credential" push origin "$sha:refs/heads/$branch" >> "$out/push-extra.log" 2>&1
    actual=$(git -C "$p" -c credential.helper= -c credential.helper="!/root/.local/share/mise/installs/github-cli-cli/2.102.0/bin/gh auth git-credential" ls-remote origin "refs/heads/$branch" | cut -f1)
    [ "$actual" = "$sha" ] || exit 1
    printf '%s\t%s\t%s\n' "$sha" "$branch" "$p" >> "$out/preserved-refs.tsv"
  done < "$out/clone-refs-$id"
  printf '%s\n' "$p" >> "$out/clones-removal-approved"
done < "$out/clones.tsv"
