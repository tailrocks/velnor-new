use std::collections::BTreeMap;
use std::error::Error;

use velnor_gen::{Drift, drift};
use velnor_model::RepoPath;

type TestResult = Result<(), Box<dyn Error>>;

const GENERATED: &str = "# Generated by velnor-gen. Change .velnor/rust-ci.toml and run `velnor-gen generate`.\nname: Rust CI\n";

#[test]
fn check_reports_each_owned_file_that_generate_would_write_or_remove() -> TestResult {
    let workflow = RepoPath::new(".github/workflows/rust-ci.yml")?;
    let other = RepoPath::new(".github/workflows/ci.yml")?;
    let expected = BTreeMap::from([(workflow.clone(), GENERATED.to_owned())]);
    let disk = |content: Option<&str>| {
        let mut files = BTreeMap::from([(other.clone(), b"name: CI\n".to_vec())]);
        if let Some(text) = content {
            files.insert(workflow.clone(), text.as_bytes().to_vec());
        }
        files
    };
    let edited = format!("{GENERATED}# edited\n");
    assert_eq!(drift(&expected, &disk(Some(GENERATED))), vec![]);
    assert_eq!(
        drift(&expected, &disk(Some(&edited))),
        vec![Drift::Changed(workflow.clone())]
    );
    assert_eq!(
        drift(&expected, &disk(None)),
        vec![Drift::Missing(workflow.clone())]
    );
    assert_eq!(
        drift(&BTreeMap::new(), &disk(Some(GENERATED))),
        vec![Drift::Stale(workflow.clone())]
    );
    assert_eq!(drift(&BTreeMap::new(), &disk(None)), vec![]);
    Ok(())
}

#[test]
fn a_file_at_an_owned_path_that_velnor_gen_did_not_write_is_never_taken_over() -> TestResult {
    let workflow = RepoPath::new(".github/workflows/rust-ci.yml")?;
    let expected = BTreeMap::from([(workflow.clone(), GENERATED.to_owned())]);
    for hand_written in [
        "name: Rust CI\n",
        "name: My own Rust CI\n# Generated by velnor-gen.\n",
    ] {
        let disk = BTreeMap::from([(workflow.clone(), hand_written.as_bytes().to_vec())]);
        assert_eq!(
            drift(&expected, &disk),
            vec![Drift::Foreign(workflow.clone())]
        );
        assert_eq!(
            drift(&BTreeMap::new(), &disk),
            vec![Drift::Foreign(workflow.clone())]
        );
    }
    Ok(())
}
