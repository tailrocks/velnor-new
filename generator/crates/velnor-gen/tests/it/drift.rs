use std::collections::BTreeMap;
use std::error::Error;

use velnor_gen::{Drift, drift};
use velnor_model::RepoPath;
use velnor_render::{Owner, VELNOR_GEN_MARKER, owner_of};

type TestResult = Result<(), Box<dyn Error>>;

const GENERATED: &str = "# Generated by velnor-gen. Change .velnor/rust-ci.toml and run `velnor-gen generate`.\nname: Rust CI\n";

#[test]
fn check_reports_each_owned_file_that_generate_would_write_or_remove() -> TestResult {
    let workflow = RepoPath::new(".github/workflows/rust-ci.yml")?;
    let other = RepoPath::new(".github/workflows/ci.yml")?;
    let expected = BTreeMap::from([(workflow.clone(), GENERATED.to_owned())]);
    let disk = |content: Option<&str>| {
        let mut files = BTreeMap::from([(other.clone(), b"name: CI\n".to_vec())]);
        if let Some(text) = content {
            files.insert(workflow.clone(), text.as_bytes().to_vec());
        }
        files
    };
    let edited = format!("{GENERATED}# edited\n");
    assert_eq!(drift(&expected, &disk(Some(GENERATED)), true), vec![]);
    assert_eq!(
        drift(&expected, &disk(Some(&edited)), true),
        vec![Drift::Changed(workflow.clone())]
    );
    assert_eq!(
        drift(&expected, &disk(None), true),
        vec![Drift::Missing(workflow.clone())]
    );
    assert_eq!(
        drift(&BTreeMap::new(), &disk(Some(GENERATED)), true),
        vec![Drift::Stale(workflow.clone())]
    );
    assert_eq!(drift(&BTreeMap::new(), &disk(None), true), vec![]);
    Ok(())
}

const ENGINE: &str =
    "# Generated by Velnor Actions 0.1.81; edit .velnor/config.toml and regenerate.\nname: CI\n";

fn path(text: &str) -> Result<RepoPath, Box<dyn Error>> {
    Ok(RepoPath::new(text)?)
}

fn disk(path: &RepoPath, text: &str) -> BTreeMap<RepoPath, Vec<u8>> {
    BTreeMap::from([(path.clone(), text.as_bytes().to_vec())])
}

#[test]
fn a_file_the_other_generator_marked_is_never_overwritten() -> TestResult {
    let workflow = path(".github/workflows/rust-ci.yml")?;
    let expected = BTreeMap::from([(workflow.clone(), GENERATED.to_owned())]);
    for hand_written in [
        ENGINE,
        "name: Rust CI\n",
        "name: Mine\n# Generated by velnor-gen.\n",
    ] {
        for engine in [false, true] {
            assert_eq!(
                drift(&expected, &disk(&workflow, hand_written), engine),
                vec![Drift::Foreign(workflow.clone())],
                "{hand_written}"
            );
        }
    }
    Ok(())
}

#[test]
fn a_marked_file_velnor_gen_does_not_write_is_stale_whatever_its_name() -> TestResult {
    let other = path(".github/workflows/release.yml")?;
    for engine in [false, true] {
        assert_eq!(
            drift(&BTreeMap::new(), &disk(&other, GENERATED), engine),
            vec![Drift::Stale(other.clone())]
        );
    }
    Ok(())
}

#[test]
fn the_engines_marked_file_is_left_alone() -> TestResult {
    let other = path(".github/workflows/ci.yml")?;
    for engine in [false, true] {
        assert_eq!(
            drift(&BTreeMap::new(), &disk(&other, ENGINE), engine),
            vec![]
        );
    }
    Ok(())
}

#[test]
fn an_unmarked_file_is_drift_only_without_the_engine_config() -> TestResult {
    let other = path(".github/workflows/release-rust-ci-tools.yml")?;
    let files = disk(&other, "name: Release\n");
    assert_eq!(
        drift(&BTreeMap::new(), &files, false),
        vec![Drift::Unmarked(other.clone())]
    );
    assert_eq!(drift(&BTreeMap::new(), &files, true), vec![]);
    Ok(())
}

#[test]
fn a_forged_header_is_not_a_velnor_gen_file_and_check_reports_it() -> TestResult {
    let workflow = path(".github/workflows/rust-ci.yml")?;
    let expected = BTreeMap::from([(workflow.clone(), GENERATED.to_owned())]);
    let forged = GENERATED.replace("Rust CI", "Evil");
    assert_eq!(
        drift(&expected, &disk(&workflow, &forged), true),
        vec![Drift::Changed(workflow.clone())]
    );
    for text in [
        "# Generated by velnor-gen.fork\nname: A\n",
        "# Generated by velnor-genie\n",
        "\n# Generated by velnor-gen.\n",
        " # Generated by velnor-gen.\n",
    ] {
        assert_eq!(owner_of(text.as_bytes()), Owner::Nobody, "{text:?}");
    }
    for text in [
        "# Generated by velnor-gen.",
        "# Generated by velnor-gen.\r\nname: A\n",
        "# Generated by velnor-gen. Change x.\n",
    ] {
        assert_eq!(owner_of(text.as_bytes()), Owner::VelnorGen, "{text:?}");
    }
    Ok(())
}

#[test]
fn each_generated_header_names_its_own_config() {
    assert!(GENERATED.starts_with(VELNOR_GEN_MARKER));
    assert!(GENERATED.lines().next().is_some_and(|first| {
        first.contains(".velnor/rust-ci.toml") && first.contains("velnor-gen generate")
    }));
}
