use std::collections::BTreeMap;

use velnor_model::{HelperRelease, RELEASE_PLZ_FILE, RELEASE_WORKFLOW_PATH, RepoPath};
use velnor_release::{ReleasePlan, RootPlan};

use crate::rules::{
    APP_TOKEN_ACTION, RenderedConcurrency, RenderedJob, RenderedStep, RenderedWorkflow,
    RuleViolation, Value, check_rules,
};
use crate::steps::{CHECKOUT, MISE, MISE_VERSION, install_helper};
use crate::workflow::yaml_job;
use crate::yaml::{Yaml, emit, entry, text};

pub const RELEASE_HEADER: &str = "# Generated by velnor-gen. Change release-plz.toml or .velnor/release.toml and run `velnor-gen generate`.\n";

const APP_TOKEN_COMMIT: &str = "64ab729a6294000f5aa4a4bc0b73d1f32bc45510";
const APP_TOKEN_VERSION: &str = "v3.3.0";
const LINT_IGNORE: &str = "jactionlint ignore=dangerous-triggers";
const ENVIRONMENT: &str = "release";
const HOSTED_RUNNER: &str = "ubuntu-latest";
const FROM_A_PASSED_PUSH: &str = "github.event.workflow_run.event == 'push' && github.event.workflow_run.conclusion == 'success'";
const STILL_NEWEST: &str = "github.event.workflow_run.head_sha == github.sha";
const VERIFIED_COMMIT: &str = "${{ github.event.workflow_run.head_sha }}";
const NEWEST_OUTPUT: &str = "steps.newest.outputs.newest == 'true'";
const GATE_IS_READY: &str = "needs.gate.outputs.ready == 'true'";
const APP_TOKEN_OUTPUT: &str = "${{ steps.app.outputs.token }}";
const GATE_TIMEOUT_MINUTES: u16 = 10;
const RELEASE_TIMEOUT_MINUTES: u16 = 30;

pub fn render_release(
    plan: &ReleasePlan,
    helper: &HelperRelease,
    branch: &str,
) -> Result<BTreeMap<RepoPath, String>, Vec<RuleViolation>> {
    let rendered = RenderedWorkflow {
        jobs: vec![gate(helper), release_pr(plan, branch), tag(plan, helper)],
    };
    check_rules(&rendered)?;
    let workflow = [
        entry("name", text("Release")),
        entry("on", trigger(plan, branch)),
        entry("permissions", Yaml::Map(Vec::new())),
        entry(
            "concurrency",
            Yaml::Map(vec![
                entry(
                    "group",
                    Yaml::Expr("release-${{ github.event.workflow_run.head_sha }}".to_owned()),
                ),
                entry("cancel-in-progress", Yaml::Bool(false)),
            ]),
        ),
        entry(
            "jobs",
            Yaml::Map(
                rendered
                    .jobs
                    .iter()
                    .map(|job| (job.id.clone(), yaml_job(job)))
                    .collect(),
            ),
        ),
    ];
    Ok(BTreeMap::from([(
        RELEASE_WORKFLOW_PATH,
        format!("{RELEASE_HEADER}{}", emit(&workflow)),
    )]))
}

fn trigger(plan: &ReleasePlan, branch: &str) -> Yaml {
    let names = |items: &[&str]| Yaml::Seq(items.iter().map(|item| text(item)).collect());
    let after: Vec<&str> = plan.after.iter().map(String::as_str).collect();
    Yaml::Map(vec![entry(
        "workflow_run",
        Yaml::Noted(
            LINT_IGNORE.to_owned(),
            Box::new(Yaml::Map(vec![
                entry("workflows", names(&after)),
                entry("types", names(&["completed"])),
                entry("branches", names(&[branch])),
            ])),
        ),
    )])
}

fn expression(condition: &str) -> String {
    format!("${{{{ {condition} }}}}")
}

fn permissions(items: &[(&str, &str)]) -> Vec<(String, String)> {
    items
        .iter()
        .map(|(scope, access)| ((*scope).to_owned(), (*access).to_owned()))
        .collect()
}

fn variables(items: &[(&str, &str)]) -> Vec<(String, Value)> {
    items
        .iter()
        .map(|(key, value)| ((*key).to_owned(), Value::Expr((*value).to_owned())))
        .collect()
}

fn gate(helper: &HelperRelease) -> RenderedJob {
    RenderedJob {
        id: "gate".to_owned(),
        condition: Some(expression(FROM_A_PASSED_PUSH)),
        permissions: permissions(&[
            ("actions", "read"),
            ("contents", "read"),
            ("statuses", "read"),
        ]),
        outputs: vec![(
            "ready".to_owned(),
            "${{ steps.gate.outputs.ready }}".to_owned(),
        )],
        runs_on: HOSTED_RUNNER.to_owned(),
        timeout_minutes: GATE_TIMEOUT_MINUTES,
        steps: vec![
            install_helper(helper),
            RenderedStep {
                id: Some("gate".to_owned()),
                name: "Check that every required check passed on the commit".to_owned(),
                env: variables(&[
                    ("GITHUB_TOKEN", "${{ github.token }}"),
                    ("REPOSITORY", "${{ github.repository }}"),
                    ("COMMIT", "${{ github.event.workflow_run.head_sha }}"),
                ]),
                run: Some(
                    "velnor-ci release-gate --repo \"$REPOSITORY\" --sha \"$COMMIT\"".to_owned(),
                ),
                ..RenderedStep::default()
            },
        ],
        ..RenderedJob::default()
    }
}

fn after_the_gate(id: &str) -> RenderedJob {
    RenderedJob {
        id: id.to_owned(),
        needs: vec!["gate".to_owned()],
        condition: Some(expression(&format!(
            "{GATE_IS_READY} && {FROM_A_PASSED_PUSH}"
        ))),
        environment: Some(ENVIRONMENT.to_owned()),
        runs_on: HOSTED_RUNNER.to_owned(),
        timeout_minutes: RELEASE_TIMEOUT_MINUTES,
        ..RenderedJob::default()
    }
}

fn release_pr(plan: &ReleasePlan, branch: &str) -> RenderedJob {
    let mut steps = vec![
        checkout(VERIFIED_COMMIT),
        newest_check(branch),
        install_release_plz(),
        on_the_default_branch(branch),
        app_token(&[("contents", "write"), ("pull-requests", "write")]),
    ];
    steps.extend(plan.roots.iter().map(|root| {
        release_plz_step(
            format!("Open the release pull request of {}", label(root)),
            format!("release-plz release-pr {}", release_plz_arguments(root)),
        )
    }));
    for step in steps.iter_mut().skip(2) {
        step.condition = Some(expression(NEWEST_OUTPUT));
    }
    RenderedJob {
        condition: Some(expression(&format!(
            "{GATE_IS_READY} && {FROM_A_PASSED_PUSH} && {STILL_NEWEST}"
        ))),
        permissions: permissions(&[("contents", "read")]),
        concurrency: Some(RenderedConcurrency {
            group: "release-pr".to_owned(),
            cancel_in_progress: false,
        }),
        steps,
        ..after_the_gate("release-pr")
    }
}

fn tag(plan: &ReleasePlan, helper: &HelperRelease) -> RenderedJob {
    let mut steps = vec![
        checkout(VERIFIED_COMMIT),
        install_release_plz(),
        install_helper(helper),
        app_token(&[("contents", "write"), ("pull-requests", "read")]),
    ];
    let files: Vec<String> = (0..plan.roots.len())
        .map(|index| format!("\"$RUNNER_TEMP/release-{index}.json\""))
        .collect();
    steps.extend(plan.roots.iter().zip(&files).map(|(root, file)| {
        release_plz_step(
            format!("Tag the releases of {}", label(root)),
            format!(
                "release-plz release {} -o json > {file}",
                release_plz_arguments(root)
            ),
        )
    }));
    steps.push(RenderedStep {
        id: Some("record".to_owned()),
        name: "Record the released packages".to_owned(),
        run: Some(format!("velnor-ci release record {}", files.join(" "))),
        ..RenderedStep::default()
    });
    let mut scopes = vec![("contents", "read")];
    if plan.roots.iter().any(|root| root.publishes_to_crates_io) {
        scopes.push(("id-token", "write"));
    }
    RenderedJob {
        permissions: permissions(&scopes),
        steps,
        ..after_the_gate("tag")
    }
}

fn newest_check(branch: &str) -> RenderedStep {
    RenderedStep {
        id: Some("newest".to_owned()),
        name: "Check that the verified commit is still the newest on the default branch".to_owned(),
        env: variables(&[
            ("GH_TOKEN", "${{ github.token }}"),
            ("REPOSITORY", "${{ github.repository }}"),
            ("COMMIT", VERIFIED_COMMIT),
        ]),
        run: Some(format!(
            "gh api \"repos/$REPOSITORY/git/ref/heads/{branch}\" --jq '\"newest=\\(.object.sha == env.COMMIT)\"' >> \"$GITHUB_OUTPUT\""
        )),
        ..RenderedStep::default()
    }
}

fn on_the_default_branch(branch: &str) -> RenderedStep {
    RenderedStep {
        name: "Move the verified commit onto the default branch".to_owned(),
        run: Some(format!("git switch --force-create {branch}")),
        ..RenderedStep::default()
    }
}

fn checkout(reference: &str) -> RenderedStep {
    RenderedStep {
        name: "Check out".to_owned(),
        uses: Some(CHECKOUT.to_owned()),
        with: vec![
            ("ref".to_owned(), Value::Expr(reference.to_owned())),
            ("fetch-depth".to_owned(), Value::Int(0)),
            ("persist-credentials".to_owned(), Value::Bool(false)),
        ],
        ..RenderedStep::default()
    }
}

fn install_release_plz() -> RenderedStep {
    RenderedStep {
        name: "Install release-plz".to_owned(),
        uses: Some(MISE.to_owned()),
        with: vec![
            ("version".to_owned(), Value::Text(MISE_VERSION.to_owned())),
            (
                "install_args".to_owned(),
                Value::Text("release-plz".to_owned()),
            ),
            ("cache".to_owned(), Value::Bool(false)),
        ],
        ..RenderedStep::default()
    }
}

fn app_token(scopes: &[(&str, &str)]) -> RenderedStep {
    let mut with = variables(&[
        ("client-id", "${{ secrets.RELEASE_APP_ID }}"),
        ("private-key", "${{ secrets.RELEASE_APP_PRIVATE_KEY }}"),
        ("owner", "${{ github.repository_owner }}"),
        ("repositories", "${{ github.event.repository.name }}"),
    ]);
    with.extend(scopes.iter().map(|(scope, access)| {
        (
            format!("permission-{scope}"),
            Value::Text((*access).to_owned()),
        )
    }));
    RenderedStep {
        id: Some("app".to_owned()),
        name: "Create the release App token".to_owned(),
        uses: Some(format!("{APP_TOKEN_ACTION}@{APP_TOKEN_COMMIT}")),
        uses_comment: Some(APP_TOKEN_VERSION.to_owned()),
        with,
        ..RenderedStep::default()
    }
}

fn release_plz_step(name: String, run: String) -> RenderedStep {
    RenderedStep {
        name,
        env: variables(&[("GITHUB_TOKEN", APP_TOKEN_OUTPUT)]),
        run: Some(run),
        ..RenderedStep::default()
    }
}

fn release_plz_arguments(root: &RootPlan) -> String {
    format!(
        "--forge github --git-token \"$GITHUB_TOKEN\" --manifest-path {} --config {}",
        shell_word(&join(&root.root, "Cargo.toml")),
        shell_word(&join(&root.root, RELEASE_PLZ_FILE))
    )
}

fn label(root: &RootPlan) -> &str {
    if root.root == "." {
        "the repository root"
    } else {
        &root.root
    }
}

fn join(root: &str, file: &str) -> String {
    if root == "." {
        file.to_owned()
    } else {
        format!("{root}/{file}")
    }
}

fn shell_word(word: &str) -> String {
    if word
        .bytes()
        .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_' | b'-' | b'/'))
    {
        word.to_owned()
    } else {
        format!("'{}'", word.replace('\'', "'\\''"))
    }
}
