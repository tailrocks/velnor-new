use std::collections::BTreeMap;

use velnor_model::{Access, PermissionScope, Permissions, RepoPath, Triggers, WorkflowPlan};

pub use crate::rules::{
    ALLOWED_ACTIONS, FETCH_HELPER_RUN, MAX_RUN_CHARACTERS, RenderedJob, RenderedStep,
    RenderedWorkflow, Rule, RuleViolation, Value, check_rules,
};
use crate::steps::rendered_job;
use crate::workflow::yaml_job;
use crate::yaml::{Yaml, emit, entry, text};

pub const WORKFLOW_PATH: RepoPath = RepoPath::from_static(".github/workflows/rust-ci.yml");
pub const OWNED_PATHS: [RepoPath; 1] = [WORKFLOW_PATH];
pub const GENERATED_HEADER: &str =
    "# Generated by velnor-gen. Change .velnor/rust-ci.toml and run `velnor-gen generate`.\n";

pub fn render(plan: &WorkflowPlan) -> Result<BTreeMap<RepoPath, String>, Vec<RuleViolation>> {
    let rendered = RenderedWorkflow {
        jobs: plan.jobs.iter().map(rendered_job).collect(),
    };
    check_rules(&rendered)?;
    let workflow = [
        entry("name", text(&plan.name)),
        entry("on", triggers(&plan.triggers)),
        entry("permissions", permissions(&plan.permissions)),
        entry(
            "concurrency",
            Yaml::Map(vec![
                entry("group", Yaml::Expr("${{ github.workflow_ref }}".to_owned())),
                entry(
                    "cancel-in-progress",
                    Yaml::Bool(plan.concurrency.cancel_in_progress),
                ),
            ]),
        ),
        entry(
            "jobs",
            Yaml::Map(
                rendered
                    .jobs
                    .iter()
                    .map(|job| (job.id.clone(), yaml_job(job)))
                    .collect(),
            ),
        ),
    ];
    Ok(BTreeMap::from([(
        WORKFLOW_PATH,
        format!("{GENERATED_HEADER}{}", emit(&workflow)),
    )]))
}

fn triggers(triggers: &Triggers) -> Yaml {
    let mut items = Vec::new();
    if triggers.pull_request {
        items.push(entry("pull_request", Yaml::Map(Vec::new())));
    }
    if triggers.workflow_dispatch {
        items.push(entry("workflow_dispatch", Yaml::Map(Vec::new())));
    }
    Yaml::Map(items)
}

fn permissions(permissions: &Permissions) -> Yaml {
    Yaml::Map(
        permissions
            .0
            .iter()
            .map(|(scope, access)| {
                let scope = match scope {
                    PermissionScope::Actions => "actions",
                    PermissionScope::Contents => "contents",
                    PermissionScope::PullRequests => "pull-requests",
                };
                let access = match access {
                    Access::None => "none",
                    Access::Read => "read",
                    Access::Write => "write",
                };
                entry(scope, text(access))
            })
            .collect(),
    )
}
