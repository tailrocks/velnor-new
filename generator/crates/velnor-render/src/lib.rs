pub fn render(plan: &WorkflowPlan) -> Result<BTreeMap<RepoPath, String>, Vec<RuleViolation>> {
    render_workflow(plan, &rendered_workflow(plan))
}

#[must_use]
pub fn rendered_workflow(plan: &WorkflowPlan) -> RenderedWorkflow {
    RenderedWorkflow {
        jobs: plan
            .jobs
            .iter()
            .map(|job| rendered_job(job, &plan.fork_runner))
            .collect(),
    }
}

pub fn render_workflow(
    plan: &WorkflowPlan,
    rendered: &RenderedWorkflow,
) -> Result<BTreeMap<RepoPath, String>, Vec<RuleViolation>> {
    check_rules(rendered)?;
    let workflow: Vec<_> = [
        Some(entry("name", text(&plan.name))),
        Some(entry("on", triggers(&plan.triggers))),
        Some(entry("permissions", permissions(&plan.permissions))),
        Some(entry("concurrency", concurrency(plan.concurrency))),
        Some(entry("env", env::workflow_env())),
        helper_integrity::defaults(&rendered.jobs).map(|defaults| entry("defaults", defaults)),
        Some(entry(
            "jobs",
            Yaml::Map(
                rendered
                    .jobs
                    .iter()
                    .map(|job| (job.id.clone(), yaml_job(job)))
                    .collect(),
            ),
        )),
    ]
    .into_iter()
    .flatten()
    .collect();
    let file = format!("{GENERATED_HEADER}{}", emit(&workflow));
    if file.len() > rules::MAX_WORKFLOW_BYTES {
        return Err(vec![RuleViolation {
            job: String::new(),
            step: 0,
            rule: Rule::WorkflowTooLarge(file.len()),
        }]);
    }
    Ok(BTreeMap::from([(WORKFLOW_PATH, file)]))
}

pub(crate) fn permission_pairs(permissions: &Permissions) -> Vec<(String, String)> {
    permissions
        .0
        .iter()
        .map(|(scope, access)| {
            let scope = match scope {
                PermissionScope::PullRequests => "pull-requests",
                PermissionScope::Actions => "actions",
                PermissionScope::Contents => "contents",
            };
            let access = match access {
                Access::None => "none",
                Access::Read => "read",
                Access::Write => "write",
            };
            (scope.to_owned(), access.to_owned())
        })
        .collect()
}

pub(crate) fn permissions(permissions: &Permissions) -> Yaml {
    Yaml::Map(
        permission_pairs(permissions)
            .iter()
            .map(|(scope, access)| entry(scope, text(access)))
            .collect(),
    )
}
