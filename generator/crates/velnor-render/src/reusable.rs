use crate::yaml::{Yaml, emit, entry, text};

const SELF_REPOSITORY_IGNORE: &str = "zizmor: ignore[self-repository]";

pub const REUSABLE_HEADER: &str =
    "# Generated by velnor-gen. Change .velnor/workflows.toml and run `velnor-gen generate`.\n";

pub fn render_reusable(
    plan: &WorkflowsPlan,
    helper: &HelperRelease,
) -> Result<Vec<(String, String)>, Vec<RuleViolation>> {
    plan.workflows
        .iter()
        .map(|workflow| render_one(workflow, helper))
        .collect()
}

fn render_one(
    workflow: &Workflow,
    helper: &HelperRelease,
) -> Result<(String, String), Vec<RuleViolation>> {
    let rendered = RenderedWorkflow {
        jobs: workflow
            .jobs
            .iter()
            .map(|job| rendered_job(workflow, job, helper))
            .collect(),
    };
    check_rules(&rendered)?;
    let mut document = vec![
        entry("name", text(&workflow.name)),
        entry("on", on(&workflow.triggers)),
        entry("permissions", Yaml::Map(Vec::new())),
    ];
    document.extend(
        crate::helper_integrity::defaults(&rendered.jobs)
            .map(|defaults| entry("defaults", defaults)),
    );
    document.extend(workflow.concurrency.as_ref().map(|concurrency| {
        entry(
            "concurrency",
            yaml_concurrency(&rendered_concurrency(concurrency)),
        )
    }));
    document.push(entry(
        "jobs",
        Yaml::Map(
            rendered
                .jobs
                .iter()
                .map(|job| (job.id.clone(), yaml_job(job)))
                .collect(),
        ),
    ));
    let file = format!("{REUSABLE_HEADER}{}", emit(&document));
    if file.len() > MAX_WORKFLOW_BYTES {
        return Err(vec![RuleViolation {
            job: String::new(),
            step: 0,
            rule: Rule::WorkflowTooLarge(file.len()),
        }]);
    }
    Ok((format!(".github/workflows/{}.yml", workflow.file), file))
}

fn rendered_concurrency(concurrency: &Concurrency) -> RenderedConcurrency {
    RenderedConcurrency {
        group: concurrency.group.clone(),
        cancel_in_progress: concurrency.cancel_in_progress,
    }
}

fn rendered_job(workflow: &Workflow, job: &Job, helper: &HelperRelease) -> RenderedJob {
    let installs = job.helper.then(|| install_helper(helper));
    let runs_on = job.runner.as_ref().unwrap_or(&workflow.runner).clone();
    RenderedJob {
        id: job.id.clone(),
        name: job.name.clone(),
        needs: job.needs.clone(),
        condition: call_fence(
            job,
            condition(workflow.condition.as_deref(), job.condition.as_deref()),
        ),
        concurrency: job.concurrency.as_ref().map(rendered_concurrency),
        environment: job.environment.clone(),
        uses: job.call.as_ref().map(|call| call_path(&call.target)),
        with: job
            .call
            .iter()
            .flat_map(|call| call_values(&call.with))
            .collect(),
        fork_runner: (!github_hosted(&runs_on)).then(|| workflow.fork_runner.clone()),
        permissions: job.permissions.clone(),
        no_permissions: job.permissions.is_empty(),
        outputs: job
            .outputs
            .iter()
            .map(|(name, value)| (name.clone(), format!("${{{{ {value} }}}}")))
            .collect(),
        matrix: job.matrix.as_ref().map(|matrix| RenderedMatrix {
            source: match &matrix.source {
                MatrixSource::Output {
                    from_job,
                    from_output,
                } => {
                    RenderedMatrixSource::Output(format!("needs.{from_job}.outputs.{from_output}"))
                }
                MatrixSource::Axes(axes) => RenderedMatrixSource::Axes(axes.clone()),
            },
            fail_fast: matrix.fail_fast,
            max_parallel: matrix.max_parallel,
        }),
        container: job.container.as_ref().map(|container| RenderedContainer {
            image: container.image.clone(),
            ports: Vec::new(),
            options: container.options.clone(),
            env: container.env.clone(),
        }),
        services: job
            .services
            .iter()
            .map(|service| {
                (
                    service.name.clone(),
                    RenderedContainer {
                        image: service.image.clone(),
                        ports: service.ports.clone(),
                        options: Some(service.options.clone()),
                        env: service.env.clone(),
                    },
                )
            })
            .collect(),
        runs_on,
        timeout_minutes: job.timeout_minutes,
        steps: match installs {
            Some(install) => crate::helper_integrity::secure_with(
                helper,
                std::iter::once(install)
                    .chain(job.steps.iter().map(rendered_step))
                    .collect(),
            ),
            None => job.steps.iter().map(rendered_step).collect(),
        },
        ..RenderedJob::default()
    }
}

/// The workflow `if` and the job `if` both have to hold.
fn condition(workflow: Option<&str>, job: Option<&str>) -> Option<String> {
    match (workflow, job) {
        (None, None) => None,
        (Some(only), None) | (None, Some(only)) => Some(format!("${{{{ {only} }}}}")),
        (Some(first), Some(second)) => Some(format!("${{{{ ({first}) && ({second}) }}}}")),
    }
}

/// A call job has no `runs-on` to put the fork fallback on, and the callee may run on a
/// self-hosted runner, so a pull request from a fork skips the call.
fn call_fence(job: &Job, condition: Option<String>) -> Option<String> {
    if job.call.is_none() {
        return condition;
    }
    all_conditions(Some(format!("${{{{ {SAME_REPOSITORY} }}}}")), condition)
}

fn call_path(target: &CallTarget) -> String {
    match target {
        CallTarget::Declared(file) => format!("./.github/workflows/{file}.yml"),
        CallTarget::Local(path) | CallTarget::Pinned(path) => path.clone(),
    }
}

fn call_values(items: &[(String, CallValue)]) -> Vec<(String, Value)> {
    items
        .iter()
        .map(|(key, value)| {
            let value = match value {
                CallValue::Text(text) => Value::Text(text.clone()),
                CallValue::Boolean(flag) => Value::Bool(*flag),
                CallValue::Number(number) => Value::Int(*number),
                CallValue::Expression(inner) => Value::Expr(format!("${{{{ {inner} }}}}")),
            };
            (key.clone(), value)
        })
        .collect()
}

fn pin(action: Action) -> String {
    let fixed = match action {
        Action::Checkout => CHECKOUT,
        Action::Mise => MISE,
        Action::UploadArtifact => UPLOAD_ARTIFACT,
        Action::DownloadArtifact => DOWNLOAD_ARTIFACT,
        Action::CacheRestore => CACHE_RESTORE,
        Action::CacheSave => CACHE_SAVE,
        Action::AttestBuildProvenance => ATTEST_BUILD_PROVENANCE,
        Action::GithubScript => {
            return format!("{}@{}", GITHUB_SCRIPT.action, GITHUB_SCRIPT.commit);
        }
    };
    fixed.to_owned()
}

fn values(items: &[(String, Env)]) -> Vec<(String, Value)> {
    items
        .iter()
        .map(|(key, value)| {
            let value = match value {
                Env::Text(value) => Value::Text(value.clone()),
                Env::Expression(inner) => Value::Expr(format!("${{{{ {inner} }}}}")),
            };
            (key.clone(), value)
        })
        .collect()
}

fn locked_off(body: &Body) -> impl Iterator<Item = (String, Value)> {
    let keys = match body {
        Body::Uses(action) => action.locked_off(),
        Body::Run(_) | Body::Local(_) | Body::Helper(_) => &[],
    };
    keys.iter()
        .map(|key| ((*key).to_owned(), Value::Bool(false)))
}

fn rendered_step(step: &Step) -> RenderedStep {
    let (uses, run) = match &step.body {
        Body::Run(run) => (None, Some(run.clone())),
        Body::Uses(action) => (Some(pin(*action)), None),
        Body::Local(action) => (Some(action.path().to_owned()), None),
        Body::Helper(command) => (None, Some(format!("velnor-ci {command}"))),
    };
    let uses_comment =
        matches!(step.body, Body::Local(_)).then(|| SELF_REPOSITORY_IGNORE.to_owned());
    RenderedStep {
        id: step.id.clone(),
        name: step.name.clone(),
        condition: step
            .condition
            .as_deref()
            .map(|condition| format!("${{{{ {condition} }}}}")),
        continue_on_error: step.continue_on_error,
        uses,
        uses_comment,
        with: values(&step.with)
            .into_iter()
            .chain(locked_off(&step.body))
            .collect(),
        env: values(&step.env),
        run,
        ..RenderedStep::default()
    }
}
